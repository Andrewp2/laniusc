#!/usr/bin/env python3
"""check_mini.lani through the verified compiler: the executable, its
program as Lean, and the gate's check of both.

    python3 -I formal/cert/mini_build.py WORKDIR [--run-all EXE] [--src-dump EXE] [--diag]
    python3 -I formal/cert/mini_build.py WORKDIR --lean      # rewrite formal/Lanius/Cert/Src.lean
    python3 -I formal/cert/mini_build.py WORKDIR --gate      # the gate step `cert`

Run from the repository root. laniusc (on the GPU lane) writes the parse
tree; the verified front end reads it; runAll's `elf` line compiles it with
`compileSource` and wraps the image (`elfFile`) as WORKDIR/check_mini.elf.
--diag prints runAll's `diag` line instead (where the front end or the
lowering stops). --lean writes the front end's program (`lake exe srcDump`)
as formal/Lanius/Cert/Src.lean, the program `checkMini_process` is about.
--gate checks that Src.lean is that program, builds the executable, and
runs it on the attack certificates (attacks.py), a certificate from gen.py
and mutants of it, against certlib's reference checker.
"""

import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FORMAL = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(FORMAL, 'tools'))
sys.path.insert(0, HERE)
import stdlib_oracle  # noqa: E402

STACK = 1 << 20
HEAP = 1 << 29     # the 2^28-byte input buffer, the stack slice, and room to spare
SRC = os.path.join(FORMAL, 'Lanius', 'Cert', 'Src.lean')
PLACEHOLDER = re.compile(r'\(Lanius\.Mini\.SrcType\.struct 1(\d{9}) \[\]\)|Lanius\.Mini\.SrcType\.struct 1(\d{9}) \[\]')
HEADER = '''import Lanius.Mini.Compiler

/-! Generated by formal/cert/mini_build.py --lean: the verified front end's
program of formal/cert/check_mini.lani (`lake exe srcDump`), the program
`Lanius.Cert.checkMini_process` is about. Function 0 is `main`. -/
'''


def option(args, name, default):
    if name in args:
        i = args.index(name)
        value = args[i + 1]
        del args[i:i + 2]
        return value
    return default


def parse(work):
    os.makedirs(work, exist_ok=True)
    base = os.path.join(work, 'check_mini')
    shutil.copy(os.path.join(HERE, 'check_mini.lani'), base + '.lani')
    stdlib_oracle.front.PARSE_SERVER.enable()
    if not stdlib_oracle.parse_checked('target/release/laniusc', base, work):
        raise SystemExit('no checked parse tree (laniusc rejected check_mini.lani?)')
    return base


def run_all(exe, work, line):
    manifest = os.path.join(work, 'manifest.txt')
    open(manifest, 'w').write(line + '\n')
    out = subprocess.run([exe, manifest], capture_output=True, text=True, timeout=240)
    if out.returncode != 0 or out.stderr.strip():
        raise SystemExit(f'runAll failed: {out.stdout}{out.stderr}')
    return out.stdout


def build_elf(exe, work, base):
    names = run_all(exe, work, f'names check_mini {base}').split('\n')
    if not names or not names[0].endswith(' app::main::main 0'):
        raise SystemExit(f'function 0 is not main (the ELF entry): {names[:1]}')
    print(run_all(exe, work, f'elf check_mini {base}.elf 0 {STACK} {HEAP} {base}').rstrip())
    if not os.path.exists(base + '.elf'):
        raise SystemExit('no executable: the verified compiler rejected the program (run with --diag)')
    os.chmod(base + '.elf', 0o755)
    return base + '.elf'


def lean_text(exe, work, base):
    manifest = os.path.join(work, 'dump.txt')
    open(manifest, 'w').write(f'check_mini {base}\n')
    out = os.path.join(work, 'Src.lean')
    run = subprocess.run([exe, manifest, out, 'Lanius.Cert'], capture_output=True, text=True, timeout=240)
    if run.returncode != 0:
        raise SystemExit(f'srcDump failed: {run.stderr}')
    text = open(out).read()
    text = PLACEHOLDER.sub(lambda m: f'ty{int(m.group(1) or m.group(2))}', text)
    text = re.sub(r'Lanius\.Mini\.(?=[A-Z][A-Za-z]*\.)', '', text)
    body = text[text.index('namespace Lanius.Cert'):]
    return HEADER + '\n' + body


def gate(elf):
    import random
    import certlib
    import gen
    problems = []
    run = subprocess.run([sys.executable, '-I', os.path.join(HERE, 'attacks.py'), elf], capture_output=True, text=True,
                         timeout=120)
    lines = run.stdout.strip().split('\n')
    bad = [x for x in lines if not x.startswith('PASS')]
    problems += [f'attacks: {x}' for x in bad]
    if run.returncode != 0 and not bad:
        problems.append(f'attacks.py failed: {run.stderr.strip()[-300:]}')
    # a small honest certificate from the search: x0 <= x1 gives x0 + 3 <= x1 + 5
    c = certlib.Cert()
    gen.signature(c)
    a = gen.Arith(c)
    x0, x1 = a.var(0), a.var(1)
    lhs, rhs = a.add(x0, a.num(3)), a.add(x1, a.num(5))
    c.theorem('t', 2, [a.le(x0, x1)], a.le(lhs, rhs), a.obligation([(x0, x1)], lhs, rhs))
    path = os.path.join(os.path.dirname(elf), 'gate.cert')
    c.write(path)
    words = certlib.read(path)
    honest = subprocess.run([elf], input=words.tobytes(), capture_output=True)
    if honest.returncode != 0 or not honest.stdout.startswith(b'ok'):
        problems.append(f'honest certificate: exit {honest.returncode}, {honest.stdout[:80]!r}')
    rng = random.Random(1104)
    agree = 0
    for _ in range(200):
        m = words.__copy__()
        i = rng.randrange(0, len(m))
        m[i] = rng.choice([m[i] + 1, max(m[i] - 1, 0), rng.randrange(0, 64), rng.randrange(0, 1 << 31), 0x7FFFFFFF])
        try:
            ref = bool(certlib.check(m))
        except (AssertionError, IndexError):
            ref = False
        got = subprocess.run([elf], input=m.tobytes(), capture_output=True).returncode
        if got in (0, 1) and (got == 0) == ref:
            agree += 1
        else:
            problems.append(f'mutant at word {i}: exit {got}, reference {ref}')
    for p in problems[:20]:
        print(p)
    print(f'cert: Src.lean current, {len(lines) - len(bad)} attack cases pass, {agree}/200 mutants agree, '
          f'{len(problems)} problems')
    return 1 if problems else 0


def main():
    args = sys.argv[1:]
    exe = option(args, '--run-all', stdlib_oracle.RUN_ALL)
    dump = option(args, '--src-dump', os.path.join(FORMAL, '.lake/build/bin/srcDump'))
    flags = {a for a in args if a.startswith('--')}
    args = [a for a in args if not a.startswith('--')]
    if len(args) != 1:
        print(__doc__.strip())
        return 2
    work = os.path.abspath(args[0])
    base = parse(work)
    if '--diag' in flags:
        print(run_all(exe, work, f'diag check_mini {base}').rstrip())
        return 0
    if '--lean' in flags:
        open(SRC, 'w').write(lean_text(dump, work, base))
        print(f'wrote {SRC}')
        return 0
    if '--gate' in flags:
        if not os.path.exists(SRC) or open(SRC).read() != lean_text(dump, work, base):
            print(f'cert: {SRC} is not the front end\'s program of check_mini.lani: run mini_build.py WORK --lean')
            return 1
        return gate(build_elf(exe, work, base))
    print(f'built {build_elf(exe, work, base)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
