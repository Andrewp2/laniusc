#!/usr/bin/env python3
"""Write TheorySound.lean: each axiom of gen.THEORY as a Lean theorem about
Nat (z = 0, b0 x = 2x, b1 x = 2x+1), so Lean checks the theory once.
    theory_lean.py OUT.lean"""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from gen import THEORY

def lean(s):
    toks = s.replace('(', ' ( ').replace(')', ' ) ').split()
    pos = 0
    def go():
        nonlocal pos
        t = toks[pos]; pos += 1
        if t != '(':
            return '0' if t == 'z' else t
        h = toks[pos]; pos += 1
        args = []
        while toks[pos] != ')':
            args.append(go())
        pos += 1
        op = {'add': '+', 'mul': '*', 'le': '≤', 'eq': '='}
        if h in op:
            return f'({args[0]} {op[h]} {args[1]})'
        if h == 'b0': return f'(2 * {args[0]})'
        if h == 'b1': return f'(2 * {args[0]} + 1)'
        raise ValueError(h)
    return go()

out = ['/-! Generated by formal/cert/theory_lean.py: the certificate theory\'s axioms hold of Nat. -/', '', 'set_option linter.unusedSimpArgs false', '']
for name, vs, hyps, concl in THEORY:
    binders = f'({vs} : Nat) ' if vs else ''
    hs = ''.join(f'(h{i} : {lean(h)}) ' for i, h in enumerate(hyps))
    out.append(f'theorem ax_{name} {binders}{hs}: {lean(concl)} := by')
    out.append('  first | omega | simp only [Nat.add_mul, Nat.mul_add, Nat.mul_assoc, Nat.two_mul, Nat.mul_comm] <;> omega | (subst_vars; rfl) | exact Nat.mul_comm _ _ | exact (Nat.mul_assoc _ _ _).symm | rw [Nat.mul_assoc, Nat.two_mul] | rw [Nat.add_mul, Nat.one_mul, Nat.mul_assoc, Nat.two_mul]')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
