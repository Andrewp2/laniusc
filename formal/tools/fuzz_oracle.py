def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('workdir')
    parser.add_argument('--count', type=int, default=40)
    parser.add_argument('--seed', type=int, default=1)
    parser.add_argument('--first', type=int, default=0, help='the first program number')
    parser.add_argument('--program', nargs='+', help='compare these files instead of generated programs')
    parser.add_argument('--bin', default='formal/.lake/build/bin', help="the directory of runAll and srcDump")
    parser.add_argument('--laniusc', default=lcc_laniusc(),
                        help="the laniusc lcc compiles with (it keys laniusc's build cache)")
    parser.add_argument('--deadline', type=float, default=240, help='seconds from the start: minimizing stops before')
    parser.add_argument('--budget', type=float, default=180,
                        help='seconds from the start: laniusc builds no more programs after')
    parser.add_argument('--found', default=FOUND)
    parser.add_argument('--no-minimize', action='store_true')
    args = parser.parse_args()
    began = time.time()
    try:
        run_cache.no_core_dumps()
    except ValueError:
        pass  # the hard limit is already 0
    so.RUN_ALL = run_cache.RUN_ALL = os.path.join(args.bin, 'runAll')
    so.SRC_DUMP = os.path.join(args.bin, 'srcDump')
    if args.bin == 'formal/.lake/build/bin':
        so.build_run_all()
    workdir = os.path.abspath(args.workdir)
    shutil.rmtree(workdir, ignore_errors=True)
    os.makedirs(workdir)

    if args.program:
        texts = [open(path).read() for path in args.program]
        ids = [os.path.basename(path) for path in args.program]
    else:
        ids = list(range(args.first, args.first + args.count))
        texts = [generate(args.seed, k) for k in ids]
    gen_s = time.time() - began
    verified = Verified(args, workdir)
    laniusc = Laniusc(args, workdir)
    t0 = time.time()
    vs = verified.compile(texts, 'p')
    compile_s = time.time() - t0
    ok = [k for k, v in enumerate(vs) if v[0] in ('elf', 'panic')]
    t0 = time.time()
    ls = laniusc.outcomes([texts[k] for k in ok], 'l', began + args.budget)
    laniusc_s = time.time() - t0

    t0 = time.time()
    found, agreed, reasons = [], 0, {}
    for k, v in enumerate(vs):
        if v[0] not in ('elf', 'panic'):
            r = v[1] if v[0] == 'noparse' else gap(verified.why(os.path.join(workdir, f'p{k}')))
            reasons[r] = reasons.get(r, 0) + 1
            open(os.path.join(workdir, 'unread.txt'), 'a').write(f'{ids[k]}: {v[0]}: {r}\n')
    known, traps, lines_out = {}, 0, 0
    skipped = sum(1 for l in ls if l[0] == 'skipped')
    for k, l in zip(ok, ls):
        if l[0] == 'skipped':
            continue
        ran = vrun(vs[k])
        traps += ran[0] in po.VERIFIED_TRAPS
        lines_out += ran[1].count(b'\n') + ran[2].count(b'\n')
        kind = verdict(vs[k], l, texts[k])
        if kind is None:
            agreed += 1
        elif isinstance(kind, tuple):
            known[kind[1]] = known.get(kind[1], 0) + 1
        else:
            found.append(dict(k=k, id=ids[k], kind=kind, text=texts[k], want=vrun(vs[k]), have=l))
    run_s = time.time() - t0

    # Confirm each alone, then minimize.
    report = []
    os.makedirs(args.found, exist_ok=True)
    for f in found:
        alone = evaluate(verified, laniusc, [f['text']], f'c{f["k"]}_')[0]
        if alone[2] != f['kind']:
            report.append(f'program {f["id"]}: {f["kind"]}, but compiled again {alone[2] or "they agree"}: '
                          f'not reproduced')
            continue
        name = f'seed{args.seed}_p{f["id"]}.lani' if not args.program else f['id']
        path = os.path.join(args.found, name)

        def save(text, done, outcome):
            v, l, want = outcome
            have = l[1] if l[0] == 'ran' else l[1][-300:]
            open(path, 'w').write(
                f'// fuzz_oracle.py --seed {args.seed}, program {f["id"]}: {f["kind"]}, {done}\n'
                f'// the verified compiler: {shown(want)}\n'
                f'// laniusc: {shown(have) if l[0] == "ran" else "rejects: " + repr(have)}\n' + text)
            return want, have, l[0]

        first = (alone[0], alone[1], vrun(alone[0]))
        save(f['text'], 'being minimized', first)
        small, outcome, done = f['text'], first, 'not minimized'
        if not args.no_minimize and not args.program:
            m = Minimizer(verified, laniusc, f['kind'], began + args.deadline,
                          lambda text: save(Minimizer.pretty(text), 'being minimized', m.outcome[text]))
            small = m.run(f['text'])
            outcome = m.outcome.get(small) or first
            small = Minimizer.pretty(small) if small in m.outcome else f['text']
            done = ('minimized' if m.complete else 'partly minimized (deadline)') + \
                f' in {m.rounds} rounds, {m.tests} candidates'
        want, have, how = save(small, done, outcome)
        report.append(f'program {f["id"]}: {f["kind"]}, {done}: {path} ({len(small.splitlines())} lines)\n'
                      f'  the verified compiler: {shown(want)}\n'
                      f'  laniusc: {shown(have) if how == "ran" else "rejects: " + repr(have[-200:])}')

    rejected = sum(1 for k, l in zip(ok, ls) if l[0] == 'rejects' and not known_reject(l[1]))
    lines = [f'{len(texts)} programs (seed {args.seed}, from {ids[0]}); time: generate {gen_s:.0f} s, '
             f'the verified compiler {compile_s:.0f} s, laniusc {laniusc_s:.0f} s ({laniusc.builds} builds, '
             f'{laniusc.build_s:.0f} s), run {run_s:.0f} s, total {time.time() - began:.0f} s',
             f'compiled by the verified compiler: {len(ok)}' +
             (f' ({sum(1 for k in ok if vs[k][0] == "panic")} with a PANIC)' if any(vs[k][0] == 'panic' for k in ok) else '') +
             f'; laniusc rejects {rejected}; both ran alike: {agreed}',
             f'of the compiled: {traps} end at a checked trap; {lines_out} lines of output in all' +
             (f'; {skipped} not built by laniusc, past --budget' if skipped else ''),
             'not compiled by the verified compiler, by the gap srcDump names:'] + \
        [f'  {n} {r}' for r, n in sorted(reasons.items(), key=lambda x: (-x[1], x[0]))]
    lines += [f'known: {n} for {what}' for what, n in sorted(known.items())]
    lines += report
    lines.append(f'{len(found)} disagreements')
    print('\n'.join(lines))
    return 1 if found else 0


if __name__ == '__main__':
    sys.exit(main())
