#!/usr/bin/env python3
"""Random programs, compiled by the verified compiler and by laniusc, run both ways.

    python3 -I formal/tools/fuzz_oracle.py WORKDIR [--count N] [--seed S] [--bin DIR] [--laniusc PATH]
        [--deadline SECONDS] [--found DIR] [--no-minimize]
    python3 -I formal/tools/fuzz_oracle.py WORKDIR --program FILE.lani...   (these programs, not minimized)

Run from the repository root. Program k of seed S is generated by its own
random stream (`random.Random(f'{S}:{k}')`), so one program is reproduced
alone with --seed S --first k --count 1.

1. Generation. Each program is one file, `module app::main;`, importing
   core::option, core::result and std::io, whose `main` returns an i32 and
   writes values to stdout and stderr as hex lines (std::io::write_byte).
   It is well typed by construction and inside the subset the verified front
   end reads (formal/tools/frontend_cases/, SEMANTIC_DECISIONS.md, the F rows
   of ROADMAP.md): integer arithmetic at every width, with overflow, division
   by zero, shifts out of range and casts between all of them; structs,
   enums with payloads of other enums, Option and Result; fields of fields;
   matches with wildcard arms and nested patterns (`V(p, Ok(q))`, the forms
   SEMANTIC_DECISIONS.md's "Nested patterns" reads, and F11b's in
   statements and lets), as expressions, statements and lets; while and for
   loops with break and continue, a while's condition sometimes more than
   its counter; `?`;
   recursion; traits with impls, generic functions with bounds and where
   clauses, inherent methods; arrays by value. Every loop is bounded and
   recursion is on a counter below 16, and a cost bound on calls in loops
   keeps a run short. Most divisors, shift amounts and indexes are made
   safe; a few are left as they come, so the traps are tested too.
   Integers lean to word boundaries (EDGES: 2^31, 2^32, 2^63, 2^64 and
   their neighbours), some written with leading zeros to 20 digits or
   more; one literal in some programs takes a form one compiler or both
   reject (EDGE_FORMS: hex, octal, binary, `_`, a suffix, past the type's
   range, 20 to 40 digits), where neither may panic.
2. The verified compiler: each program is parsed on the CPU (Parser: the
   Lean lexer's tokens from runAll's `dump`, laniusc's LL(1) table; no GPU
   job), the verified validator checks each tree as it checks laniusc's,
   and one runAll manifest compiles every program to a Linux executable
   (`elf`, as programs_oracle.py does). For a program the front end does
   not read, srcDump says why. A PANIC line from runAll (a Lean panic, after
   which the run goes on with a default value) marks its program, found by
   compiling each alone, as a disagreement whatever laniusc does.
3. laniusc: each program the verified compiler compiled is built alone
   through target/claude-work/bin/lcc, the resident laniusc (tens of
   milliseconds a build; it holds heavy's GPU lock while it compiles, so
   GPU jobs never run in parallel).
4. Both run with no input; they must end alike: the same exit status (or
   signal), or both at a checked trap (programs_oracle.VERIFIED_TRAPS,
   LANIUSC_TRAPS), and the same bytes on stdout and stderr. A program the
   verified compiler compiles and laniusc rejects disagrees too.
5. A disagreement is confirmed by compiling the program again alone with
   both compilers, then minimized by hierarchical delta debugging over its
   lines (items, then statements, then the statements of their blocks), each
   round's candidates compiled together, until --deadline; it is saved under
   --found (default target/claude-work/fuzz/found/) with both outcomes in a
   comment.

Known differences, which the generator steers around so that the rest of
a program is still compared (each was found by this fuzzer; the programs are
in target/claude-work/fuzz/found/):
- Store order. For `a[i] = v` with i past the end, Core checks the bound
  before it evaluates v (SEMANTIC_DECISIONS.md, "Traps in compiled code");
  laniusc evaluates v first, as Rust does, so v's output (or v's own trap)
  comes before laniusc's trap. The front end no longer reads a store whose
  value calls a function, and the generator writes none; a program that
  still shows the order is counted as known (store_order_known).
- Bare shift amounts, a verified-compiler reading bug (ROADMAP.md, "Bare
  shift amounts"; found/bare_amount_*.lani), fixed in bcd36a2b0: amounts
  are written bare again (BARE_AMOUNTS).
- Fixed laniusc bugs this generator found keep regression fixtures in
  tests/fixtures/compiler_defects/ (lnc0005_nested_variant_pattern.lani,
  lnc0017_payload_after_nested_variant.lani); nothing works around them.
- Constant traps. laniusc rejects a constant divisor of zero and a constant
  index past the end at compile time (KNOWN_REJECTS); Core traps when the
  program runs. Divisors and indexes that may trap are computed.
- Path calls of methods. laniusc rejects `T::m(x, ..)` and `S::m(x, ..)`
  for a method m that takes self (LNC0027, call resolution failed; not yet
  implemented, generics backlog b14); the verified front end reads them as
  `x.m(..)`. Methods are called with a dot.
- Literal typing. laniusc types a bare literal by its context only in some
  places: not in Some(..), Ok(..), Err(..), nor as a match arm's value
  outside a typed let; there the generator writes no bare literal.
And gaps of the verified compiler, which rejects (never miscompiles): a
store of a struct, enum or array into a field, `bool as` an integer, a
constant whose value is a parenthesized wide literal, type arguments
inferred from an expression that is not a local.

Prints a summary; exits nonzero on a disagreement.
"""

