# ---------------------------------------------------------------- types

def is_int(t):
    return t in INTS


def array_parts(t):
    m = re.fullmatch(r'\[(.+); (\d+)\]', t)
    return (m.group(1), int(m.group(2))) if m else None


def option_of(t):
    return t[len(OPTION):-1] if t and t.startswith(OPTION) else None


def result_of(t):
    if not t or not t.startswith(RESULT):
        return None
    a, b = so.split_top(t[len(RESULT):-1])
    return a, b


# Word boundaries near which int_value picks values.
EDGES = [1 << 31, 1 << 32, 1 << 53, 1 << 63, 10 ** 18, 10 ** 19, (1 << 64) - 1]
# The forms edge_form writes: the verified front end reads none of hex,
# octal, binary or `_`; neither compiler reads a suffix; the rest are out of
# the type's range.
EDGE_FORMS = ['hex', 'octal', 'binary', 'underscore', 'suffix', 'over', 'over-hex', 'wide', 'wide']


def bounds(t):
    w, s = INTS[t]
    return (-(1 << (w - 1)), (1 << (w - 1)) - 1) if s else (0, (1 << w) - 1)


def wrap(v, t):
    w, s = INTS[t]
    v &= (1 << w) - 1
    return v - (1 << w) if s and v >> (w - 1) else v


# ---------------------------------------------------------------- generator

class Fn:
    def __init__(self, name, params, ret, kind='plain', cost=1, generic=None):
        self.name, self.params, self.ret, self.kind, self.cost = name, params, ret, kind, cost
        self.generic = generic  # (trait, bound type parameter) for a generic function


class Scope:
    def __init__(self, fn, ret):
        self.fn, self.ret = fn, ret
        self.frames = [{}]
        self.loop = 0
        self.mult = 1
        self.names = 0
        self.self_type = None

    def fresh(self, prefix='l'):
        self.names += 1
        return f'{prefix}{self.names}'

    def bind(self, name, t):
        self.frames[-1][name] = t

    def vars(self, pred=None):
        out = []
        for frame in self.frames:
            for name, t in frame.items():
                if pred is None or pred(t):
                    out.append((name, t))
        return out

    def push(self):
        self.frames.append({})

    def pop(self):
        self.frames.pop()


class Gen:
    """One program's generator: its declarations, then its text."""

    def __init__(self, rng):
        self.rng = rng
        self.structs = {}   # name -> [(field, type)]
        self.enums = {}     # name -> [(variant, [types])]
        self.consts = {}    # name -> type
        self.fns = []       # callable top-level functions, in order (a function calls earlier ones)
        self.traits = {}    # name -> dict(method, self_form, ret, impls=[types])
        self.methods = {}   # struct -> [Fn] (inherent, first param self)
        self.items = []
        self.counter = 0
        self.err = rng.choice(['i32', 'u8', 'u16', 'i64'])
        # The program's feature weights: each program leans its own way.
        self.w = {k: rng.choice([0.3, 1, 1, 2, 4]) for k in
                  ('arith', 'shift', 'div', 'cast', 'struct', 'enum', 'array', 'match', 'loop', 'try', 'rec', 'nest',
                   'trait', 'call', 'emit', 'tap', 'edge')}
        # Some programs write one literal in a form the verified front end
        # does not read (hex, `_`, a suffix) or out of its type's range
        # (EDGE_FORMS): both compilers should reject it, and neither panic.
        self.exotic = 1 if rng.random() < 0.06 else 0
        self.taps = {}      # type -> an identity function that writes a tag to stderr first
        self.tags = 0
        self.depth = rng.choice([2, 2, 3, 4])  # how deep a statement's expressions nest
        self.safe = rng.choice([0.99, 0.97, 0.93])  # how often a divisor, shift or index is made safe

    def name(self, prefix):
        self.counter += 1
        return f'{prefix}{self.counter}'

    def chance(self, p):
        return self.rng.random() < p

    def pick(self, options):
        """A weighted choice of (weight, value) pairs."""
        total = sum(w for w, _ in options)
        r = self.rng.random() * total
        for w, v in options:
            r -= w
            if r <= 0:
                return v
        return options[-1][1]

    # ------------------------------------------------ types

    def int_type(self):
        return self.rng.choice(INT_NAMES + ['i32', 'i32', 'u8', 'u64'])

    def scalar_type(self):
        return 'bool' if self.chance(0.15) else self.int_type()

    def value_type(self, depth=1):
        """A type for a local, a parameter or a result."""
        opts = [(6, 'int'), (1, 'bool')]
        if self.structs:
            opts.append((2 * self.w['struct'], 'struct'))
        if self.enums:
            opts.append((2 * self.w['enum'], 'enum'))
        if depth > 0:
            opts.append((self.w['array'], 'array'))
            opts.append((0.5 * self.w['try'], 'option'))
            opts.append((0.5 * self.w['try'], 'result'))
        k = self.pick(opts)
        if k == 'int':
            return self.int_type()
        if k == 'bool':
            return 'bool'
        if k == 'struct':
            return self.rng.choice(sorted(self.structs))
        if k == 'enum':
            return self.rng.choice(sorted(self.enums))
        if k == 'array':
            return f'[{self.scalar_type()}; {self.rng.choice([1, 2, 3, 4, 4, 4, 5, 8, 16])}]'
        if k == 'option':
            return f'{OPTION}{self.value_type(0)}>'
        return f'{RESULT}{self.value_type(0)}, {self.err}>'

    # ------------------------------------------------ literals

    def int_value(self, t):
        lo, hi = bounds(t)
        w = INTS[t][0]
        if self.chance(0.06 * self.w['edge']):
            # near a word boundary: 2^31, 2^32, 2^63, 2^64 and their neighbours
            near = [v for e in EDGES for v in (e - 1, e, e + 1, -e, 1 - e) if lo <= v <= hi]
            return self.rng.choice(near + [lo, hi, lo + 1, hi - 1])
        k = self.rng.randrange(8)
        if k == 0:
            return self.rng.choice([lo, hi, lo + 1, hi - 1])
        if k == 1:
            return self.rng.choice([0, 1, 2, 3]) if lo == 0 else self.rng.choice([0, 1, -1, 2, -2])
        if k == 2:
            v = 1 << self.rng.randrange(w)
            return wrap(self.rng.choice([v, v - 1, -v]), t)
        if k <= 5:
            return self.rng.randrange(max(lo, -100), min(hi, 100) + 1)
        return self.rng.randrange(lo, hi + 1)

    def lit(self, t, value=None):
        if t == 'bool':
            return self.rng.choice(['true', 'false'])
        v = self.int_value(t) if value is None else value
        text = str(abs(v))
        if self.exotic and self.chance(0.05):
            self.exotic = 0
            text = self.edge_form(t, abs(v), v < 0)
        elif self.chance(0.02 * self.w['edge']):
            # leading zeros, often to 20 digits or more (wide_decimal's path)
            text = '0' * self.rng.choice([1, 3, 17, 19, 20, 25]) + text
        return f'(-{text})' if v < 0 else text

    def edge_form(self, t, a, negative):
        """A literal in a form one compiler or both reject (EDGE_FORMS)."""
        lo, hi = bounds(t)
        top = -lo if negative else hi
        k = self.rng.choice(EDGE_FORMS)
        if k == 'hex':
            h = f'{a:x}'
            return '0x' + '0' * self.rng.choice([0, 0, 5]) + (h.upper() if self.chance(0.5) else h)
        if k == 'octal':
            return f'0o{a:o}'
        if k == 'binary':
            return f'0b{a:b}'
        if k == 'underscore':
            d = str(a)
            return f'{a:_}' if a >= 1000 else d[0] + '_' + d[1:] if len(d) > 1 else d + '_'
        if k == 'suffix':
            return f'{a}{t}'
        if k == 'over':
            return str(top + 1)
        if k == 'over-hex':
            return f'0x{top + 1:x}'
        # 'wide': 20 or more digits, past 2^64
        return str(self.rng.choice([1 << 64, (1 << 64) + 9, 99999999999999999999,
                                    10 ** self.rng.randrange(20, 40) + self.rng.randrange(10 ** 6)]))

    # ------------------------------------------------ expressions

    def expr(self, s, t, d, anchor=False):
        """An expression of type t. With anchor, one whose type its own atoms
        decide (no bare literal), for a cast, a comparison or a shift amount."""
        if is_int(t):
            return self.int_expr(s, t, d, anchor)
        if t == 'bool':
            return self.bool_expr(s, d)
        return self.agg_expr(s, t, d)

    def atoms(self, s, t):
        """Expressions of type t that are names: locals, constants, fields, elements."""
        out = [n for n, vt in s.vars() if vt == t]
        out += [c for c, ct in self.consts.items() if ct == t]
        for n, vt in s.vars():
            if vt in self.structs:
                out += [f'{n}.{f}' for f, ft in self.structs[vt] if ft == t]
                # a field of a field
                out += [f'{n}.{f}.{g}' for f, ft in self.structs[vt] if ft in self.structs
                        for g, gt in self.structs[ft] if gt == t]
            a = array_parts(vt)
            if a and a[0] == t:
                out.append(f'{n}[{self.index(s, a[1])}]')
        return out

    def index(self, s, n, d=1):
        """An index into an array of n elements: in range but for a few
        (self.wild says whether this one may not be)."""
        it = self.rng.choice(['i32', 'usize'])
        self.wild = False
        if self.chance(self.safe):
            if n & (n - 1) == 0 and d > 0 and self.chance(0.6):
                e = self.int_expr(s, it, d - 1, True)
                return f'({e} & {n - 1})'
            return str(self.rng.randrange(n))
        # computed: laniusc rejects a constant index past the end at compile time
        self.wild = True
        if d > 0 and self.chance(0.5):
            return self.int_expr(s, it, d - 1, True)
        return f'({self.rng.choice(["i32", "usize"]) and str(self.rng.choice([n, n + 1, 255]))} as {it})'

    def calls_to(self, s, t):
        """The functions callable here that return t."""
        out = []
        for f in self.fns:
            if f.ret == t and f.cost * s.mult <= 4000 and f.name != s.fn:
                out.append(f)
        return out

    def call(self, s, f, d):
        if f.kind == 'rec':
            # the first argument is the depth counter
            rest = ', '.join(self.expr(s, pt, d - 1) for _, pt in f.params[1:])
            counter = self.int_expr(s, 'i32', d - 1, True) if d > 1 else self.lit('i32')
            return f'{f.name}(({counter} & 15){", " + rest if rest else ""})'
        if f.kind == 'generic':
            trait, impls = f.generic
            x = self.rng.choice(impls)
            ft = x if f.params[0][1] == 'T' else f.params[0][1]
            # the front end infers a type argument from a local, not from any expression
            names = [n for n, vt in s.vars() if vt == ft]
            targs = f'<{x}>' if self.chance(0.3) or not names else ''
            first = self.rng.choice(names) if not targs else self.expr(s, ft, d - 1)
            rest = ', '.join(self.expr(s, pt, d - 1) for _, pt in f.params[1:])
            return f'{f.name}{targs}({first}{", " + rest if rest else ""})'
        return f'{f.name}({", ".join(self.expr(s, pt, d - 1) for _, pt in f.params)})'

    def method_calls(self, s, t, d):
        """Calls of methods returning t on locals: inherent and trait methods."""
        out = []
        for n, vt in s.vars():
            for m in self.methods.get(vt, []):
                if m.ret == t and m.cost * s.mult <= 4000 and m.kind == 'method':
                    # laniusc reads no `S::m(x, ..)` for a method with self
                    args = ', '.join(self.expr(s, pt, d - 1) for _, pt in m.params[1:])
                    out.append(f'{n}.{m.name}({args})')
        for vt, ms in self.methods.items():
            for m in ms:
                if m.ret == t and m.cost * s.mult <= 4000 and m.kind == 'static' and m.name != s.fn:
                    args = ', '.join(self.expr(s, pt, d - 1) for _, pt in m.params)
                    out.append(f'{vt}::{m.name}({args})')
        for tn, tr in self.traits.items():
            if tr['ret'] != t:
                continue
            for x in tr['impls']:
                cands = [n for n, vt in s.vars() if vt == x]
                if tr['self_form'] and cands:
                    n = self.rng.choice(cands)
                    k = self.expr(s, 'i32', d - 1)
                    out.append(f'{n}.{tr["method"]}({k})')
                elif not tr['self_form'] and (cands or is_int(x)):
                    arg = self.expr(s, x, d - 1, anchor=True)
                    out.append(f'{x}::{tr["method"]}({arg})')
        # inside a generic function: T::m(x) on the bound's trait
        if s.self_type and s.self_type[0] == 'T':
            trait = self.traits[s.self_type[1]]
            if trait['ret'] == t:
                xs = [n for n, vt in s.vars() if vt == 'T']
                if xs:
                    x = self.rng.choice(xs)
                    if trait['self_form']:
                        # laniusc reads no `T::m(x, k)` for a method with self
                        out.append(f'{x}.{trait["method"]}({self.expr(s, "i32", d - 1)})')
                    else:
                        out.append(f'T::{trait["method"]}({x})')
        return out

    def scrutinees(self, s, d):
        """(text, type) of enum, Option or Result values to match on."""
        out = [(n, vt) for n, vt in s.vars() if vt in self.enums or option_of(vt) or result_of(vt)]
        if d > 0:
            for f in self.fns:
                if (f.ret in self.enums or option_of(f.ret) or result_of(f.ret)) and f.cost * s.mult <= 4000 \
                        and f.name != s.fn and self.chance(0.3):
                    out.append((self.call(s, f, d), f.ret))
        return out

    def variants(self, t):
        if t in self.enums:
            return self.enums[t]
        o = option_of(t)
        if o:
            return [('Some', [o]), ('None', [])]
        ok, err = result_of(t)
        return [('Ok', [ok]), ('Err', [err])]

    def arms(self, s, t, statement=False):
        """The arms of a match on t, in some order, maybe ending in a wildcard:
        (pattern, binders) for each, None for the wildcard. A variant whose
        payload holds an enum may get nested arms (SEMANTIC_DECISIONS.md,
        "Nested patterns"): one per inner variant, the same binders in the
        other columns, ending, when the inner variants are not all named, in
        a binder there that its value does not use, or in the outer wildcard.
        In a statement's or a let's match (F11b) a nested arm binds at most one."""
        vs = list(self.variants(t))
        self.rng.shuffle(vs)
        named = vs
        if len(vs) > 1 and self.chance(0.5 * self.w['match'] / (1 + self.w['match'])):
            named = vs[:self.rng.randrange(1, len(vs))]
            if statement and any(len(ps) > 1 for _, ps in vs[len(named):]):
                named = vs
        wildcard = len(named) < len(vs)
        out = []
        for v, ps in named:
            q = f'{t}::{v}' if t in self.enums and self.chance(0.3) else v
            nested = self.nested_arms(s, t, q, ps, wildcard, statement)
            if nested:
                out += nested
                continue
            binders = [(s.fresh('p'), pt) for pt in ps]
            out.append((f'{q}({", ".join(b for b, _ in binders)})' if ps else q, binders))
        if wildcard:
            out.append(('_', []))
        return out

    @staticmethod
    def enum_path(t):
        """The path of t's enum, for a qualified variant."""
        if option_of(t):
            return 'core::option::Option'
        if result_of(t):
            return 'core::result::Result'
        return t

    def nested_arms(self, s, t, q, ps, wildcard, statement):
        """Nested arms for the variant q of t with payload types ps, or None."""
        cols = [j for j, pt in enumerate(ps) if pt in self.enums or option_of(pt) or result_of(pt)]
        if not cols or not self.chance(min(0.8, 0.2 * self.w['nest'])):
            return None
        j = self.rng.choice(cols)
        if statement and (len(ps) > 1 or any(len(ips) > 1 for _, ips in self.variants(ps[j]))):
            return None
        others = [(s.fresh('p'), pt) for pt in ps]
        inner = list(self.variants(ps[j]))
        self.rng.shuffle(inner)
        some = inner[:self.rng.randrange(1, len(inner) + 1)]
        out = []
        if statement and self.chance(0.15):
            # a plain arm first: it takes every value of the variant (F11b)
            plain = [(s.fresh('p'), pt) for pt in ps]
            out.append((f'{q}({", ".join(b for b, _ in plain)})', plain))
        for iv, ips in some:
            # Mostly bare, as written; sometimes qualified.
            iq = f'{self.enum_path(ps[j])}::{iv}' if self.chance(0.25) else iv
            ib = [(s.fresh('p'), ipt) for ipt in ips]
            cells = [b for b, _ in others]
            cells[j] = f'{iq}({", ".join(b for b, _ in ib)})' if ips else iq
            out.append((f'{q}({", ".join(cells)})', [x for k, x in enumerate(others) if k != j] + ib))
        if len(some) < len(inner) and (not wildcard or self.chance(0.5)):
            # the binder at j is read as `_`: its value must not spell it, so it is not bound
            out.append((f'{q}({", ".join(b for b, _ in others)})', [x for k, x in enumerate(others) if k != j]))
        return out

    def match_expr(self, s, t, d):
        scr = self.scrutinees(s, d)
        if not scr:
            return None
        text, st = self.rng.choice(scr)
        parts = []
        for pat, binders in self.arms(s, st):
            s.push()
            for b, bt in binders:
                s.bind(b, bt)
            # laniusc types no literal arm of a match by its context or another arm
            parts.append(f'{pat} -> {self.expr(s, t, d - 1, anchor=True)}')
            s.pop()
        # parenthesized: after a match's `}` laniusc reads `+` as a prefix
        return f'(match ({text}) {{ {", ".join(parts)} }})'

    def int_expr(self, s, t, d, anchor=False):
        w = self.w
        atoms = self.atoms(s, t)
        opts = []
        if not anchor:
            opts.append((3 if d <= 0 else 1, 'lit'))
        if atoms:
            opts.append((6 if d <= 0 else 3, 'atom'))
        if d > 0:
            opts += [(3 * w['arith'], 'arith'), (1.5 * w['arith'], 'bits'), (w['shift'], 'shift'),
                     (w['div'], 'div'), (1.5 * w['cast'], 'cast')]
            if INTS[t][1]:
                opts.append((0.5 * w['arith'], 'neg'))
            opts.append((0.4 * w['tap'], 'tap'))
            if self.calls_to(s, t):
                opts.append((2 * w['call'], 'call'))
            if self.method_calls(s, t, 0):
                opts.append((1.5 * w['trait'], 'method'))
            if self.scrutinees(s, 0) and not anchor:
                opts.append((w['match'], 'match'))
        if not opts or (anchor and not atoms and d <= 0):
            # A cast of a local or of an i32 literal decides its own type.
            others = [n for n, vt in s.vars() if is_int(vt)]
            if others and self.chance(0.7):
                return f'({self.rng.choice(others)} as {t})'
            return f'({self.lit("i32")} as {t})'
        k = self.pick(opts)
        if k == 'lit':
            return self.lit(t)
        if k == 'atom':
            return self.rng.choice(atoms)
        if k in ('arith', 'bits'):
            op = self.rng.choice(['+', '-', '*'] if k == 'arith' else ['&', '|', '^'])
            a, b = self.int_expr(s, t, d - 1, anchor), self.int_expr(s, t, d - 1)
            if self.chance(0.5):
                a, b = b, a
                if anchor and not self.anchored(a):
                    a, b = b, a
            return f'({a} {op} {b})'
        if k == 'shift':
            op = self.rng.choice(['<<', '>>'])
            a = self.int_expr(s, t, d - 1, anchor)
            width = INTS[t][0]
            if self.chance(0.4):
                amt = str(self.rng.randrange(width) if self.chance(self.safe) else
                          self.rng.choice([width, width + 1, 255]))
            else:
                at = self.int_type()
                amt = self.int_expr(s, at, d - 1, True)
                if self.chance(self.safe):
                    amt = f'({amt} & {width - 1})'
                if not BARE_AMOUNTS:
                    # An amount whose atoms are constants and literals (a local
                    # inside a shift of its own does not count) the front end
                    # reads at the shifted value's type (ROADMAP): the cast decides it.
                    amt = f'({amt} as {at})'
            return f'({a} {op} {amt})'
        if k == 'div':
            op = self.rng.choice(['/', '%'])
            a = self.int_expr(s, t, d - 1, anchor)
            if INTS[t][1] and not self.chance(self.safe):
                # the least value over -1, signed overflow; through taps, so not a constant
                lo = bounds(t)[0]
                return f'({self.tap(s, t, self.lit(t, lo))} {op} {self.tap(s, t, self.lit(t, -1))})'
            if self.chance(self.safe):
                b = self.rng.choice([self.lit(t, self.nonzero(t)), f'({self.int_expr(s, t, d - 1)} | 1)'])
            else:
                # not a bare literal: laniusc rejects a constant zero divisor (KNOWN_REJECTS)
                b = self.int_expr(s, t, d - 1, True)
            return f'({a} {op} {b})'
        if k == 'tap':
            return self.tap(s, t, self.int_expr(s, t, d - 1, anchor))
        if k == 'neg':
            return f'(-{self.int_expr(s, t, d - 1, anchor)})'
        if k == 'cast':
            src = self.int_type()
            return f'({self.int_expr(s, src, d - 1, True)} as {t})'
        if k == 'call':
            return self.call(s, self.rng.choice(self.calls_to(s, t)), d)
        if k == 'method':
            return self.rng.choice(self.method_calls(s, t, d))
        if k == 'match':
            return self.match_expr(s, t, d) or self.lit(t)
        raise AssertionError(k)

    def tap(self, s, t, e):
        """e through an identity function that first writes a tag to stderr:
        the order of the tags is the order of evaluation."""
        if t not in self.taps:
            name = self.taps[t] = self.name('tap')
            self.items.append(f'fn {name}(v: {t}, tag: u32) -> {t} {{\n    out_err(tag);\n    return v;\n}}')
        self.tags += 1
        return f'{self.taps[t]}({e}, {self.tags})'

    def nonzero(self, t):
        v = 0
        while v == 0:
            v = self.int_value(t)
        return v

    @staticmethod
    def anchored(text):
        # A name, a call or a cast decides the type; literals alone, as in
        # `(15 & 89)`, do not (laniusc types them from no sibling in Err(..)).
        return re.search(r'[A-Za-z_]', text) is not None

    def bool_expr(self, s, d, anchor=False):
        atoms = self.atoms(s, 'bool')
        opts = [] if anchor else [(2 if d <= 0 else 0.5, 'lit')]
        if atoms:
            opts.append((4, 'atom'))
        if d > 0:
            opts += [(5, 'cmp'), (1, 'not'), (2, 'logic'), (0.5, 'eq'), (0.3 * self.w['tap'], 'tap')]
            if self.calls_to(s, 'bool'):
                opts.append((1, 'call'))
            if self.scrutinees(s, 0):
                opts.append((0.5 * self.w['match'], 'match'))
        if not opts:
            return self.cmp(s, 1)
        k = self.pick(opts)
        if k == 'lit':
            return self.lit('bool')
        if k == 'atom':
            return self.rng.choice(atoms)
        if k == 'cmp':
            return self.cmp(s, d)
        if k == 'tap':
            return self.tap(s, 'bool', self.bool_expr(s, d - 1, anchor))
        if k == 'not':
            return f'(!{self.bool_expr(s, d - 1, anchor)})'
        if k == 'logic':
            return f'({self.bool_expr(s, d - 1, anchor)} {self.rng.choice(["&&", "||"])} {self.bool_expr(s, d - 1)})'
        if k == 'eq':
            return f'({self.bool_expr(s, d - 1, True)} {self.rng.choice(["==", "!="])} {self.bool_expr(s, d - 1)})'
        if k == 'call':
            return self.call(s, self.rng.choice(self.calls_to(s, 'bool')), d)
        return self.match_expr(s, 'bool', d) or 'true'

    def cmp(self, s, d):
        t = self.int_type()
        a, b = self.int_expr(s, t, d - 1, True), self.int_expr(s, t, d - 1)
        if self.chance(0.5):
            a, b = b, a
        return f'({a} {self.rng.choice(["<", "<=", ">", ">=", "==", "!="])} {b})'

    def agg_expr(self, s, t, d):
        names = [n for n, vt in s.vars() if vt == t]
        for n, vt in s.vars():
            if vt in self.structs:
                names += [f'{n}.{f}' for f, ft in self.structs[vt] if ft == t]
        calls = self.calls_to(s, t) if d > 0 else []
        k = self.pick([(3 if names else 0, 'name'), (2 * self.w['call'] if calls else 0, 'call'), (3, 'make')])
        if k == 'name':
            return self.rng.choice(names)
        if k == 'call':
            return self.call(s, self.rng.choice(calls), d)
        if t in self.structs:
            fields = ', '.join(f'{f}: {self.expr(s, ft, d - 1)}' for f, ft in self.structs[t])
            return f'{t.split("<")[0]} {{ {fields} }}'
        a = array_parts(t)
        if a:
            et, n = a
            if self.chance(0.3):
                return f'[{self.lit(et)}; {n}]'
            return '[' + ', '.join(self.expr(s, et, d - 1) for _ in range(n)) + ']'
        v, ps = self.rng.choice(self.variants(t))
        q = f'{t}::{v}' if t in self.enums and self.chance(0.3) else v
        if not ps:
            return q
        # laniusc does not type a literal in Some(..), Ok(..) or Err(..) by its context
        generic = t not in self.enums
        return f'{q}({", ".join(self.expr(s, pt, d - 1, anchor=generic) for pt in ps)})'

    # ------------------------------------------------ statements

    def block(self, s, n, d, ind, tail=None):
        """n statements at indentation ind, in a new scope; tail is a final
        statement kind ('return', 'break', 'continue') or None."""
        s.push()
        out = []
        for _ in range(n):
            out += self.stmt(s, d, ind)
        if tail == 'return':
            out += self.returns(s, d, ind)
        elif tail in ('break', 'continue'):
            out.append(ind + tail + ';')
        s.pop()
        return out

    def ret_value(self, s):
        return self.expr(s, s.ret, self.depth)

    def stmt(self, s, d, ind):
        w = self.w
        opts = [(6, 'let'), (3, 'assign'), (2 * w['emit'], 'emit'), (1, 'compound')]
        if any(vt in self.structs for _, vt in s.vars()):
            opts.append((1.5 * w['struct'], 'field'))
        if any(array_parts(vt) for _, vt in s.vars()):
            opts.append((1.5 * w['array'], 'store'))
        if d > 0:
            opts += [(2, 'if'), (1.5 * w['loop'], 'while'), (w['loop'], 'for'), (0.3, 'block')]
            if s.ret:
                opts.append((0.7, 'early'))
            if s.loop:
                opts.append((1.5 * w['loop'], 'jump'))
        if s.ret and (option_of(s.ret) or result_of(s.ret)) and self.try_callees(s):
            opts.append((3 * w['try'], 'try'))
        if self.calls_to_any(s):
            opts.append((w['call'], 'callstmt'))
        opts.append((0.3, 'write'))
        k = self.pick(opts)
        return getattr(self, 's_' + k)(s, d, ind)

    def s_let(self, s, d, ind):
        t = self.value_type()
        name = s.fresh()
        if self.chance(0.15):
            # an untyped let of a value whose type no literal decides
            cands = [f for f in self.fns if f.cost * s.mult <= 4000 and f.name != s.fn and f.ret]
            if cands:
                f = self.rng.choice(cands)
                text = self.call(s, f, 2)
                s.bind(name, f.ret)
                return [ind + f'let {name} = {text};']
        if (t in self.enums or option_of(t) or result_of(t)) and s.ret and self.chance(0.1 * self.w['match']):
            out = self.let_match(s, name, d, ind)
            if out:
                return out
        e = self.expr(s, t, self.depth)
        s.bind(name, t)
        return [ind + f'let {name}: {t} = {e};']

    def let_match(self, s, name, d, ind):
        """let x: T = match (e) { one value arm, the others blocks that return };"""
        scr = self.scrutinees(s, 1)
        if not scr:
            return None
        text, st = self.rng.choice(scr)
        t = self.value_type(0)
        arms = self.arms(s, st, statement=True)
        if any(len(b) > 1 for _, b in arms):
            return None
        value_arm = self.rng.randrange(len(arms))
        out = [ind + f'let {name}: {t} = match ({text}) {{']
        for i, (pat, binders) in enumerate(arms):
            s.push()
            for b, bt in binders:
                s.bind(b, bt)
            if i == value_arm:
                out.append(ind + f'    {pat} -> {self.expr(s, t, self.depth)},')
            else:
                out.append(ind + f'    {pat} -> {{')
                out += self.block(s, self.rng.randrange(2), d - 1, ind + '        ', 'return')
                out.append(ind + '    },')
            s.pop()
        out.append(ind + '};')
        s.bind(name, t)
        return out

    def assignable(self, s, pred):
        return [n for n, t in s.vars(pred) if n.startswith('l')]

    def s_assign(self, s, d, ind):
        names = self.assignable(s, lambda t: True)
        if not names:
            return self.s_let(s, d, ind)
        n = self.rng.choice(names)
        t = dict(s.vars())[n]
        return [ind + f'{n} = {self.expr(s, t, self.depth)};']

    def s_compound(self, s, d, ind):
        names = self.assignable(s, is_int)
        if not names:
            return self.s_let(s, d, ind)
        n = self.rng.choice(names)
        t = dict(s.vars())[n]
        op = self.rng.choice(['+', '-', '*', '/', '%', '&', '|', '^', '<<', '>>'])
        if op in '/%':
            e = self.lit(t, self.nonzero(t)) if self.chance(self.safe) else self.int_expr(s, t, 1)
        elif op in ('<<', '>>'):
            e = str(self.rng.randrange(INTS[t][0])) if self.chance(self.safe) else self.int_expr(s, t, 1)
        else:
            e = self.int_expr(s, t, self.depth)
        return [ind + f'{n} {op}= {e};']

    def s_field(self, s, d, ind):
        cands = [(n, vt) for n, vt in s.vars() if vt in self.structs and n in self.assignable(s, lambda t: True)]
        if not cands:
            return self.s_emit(s, d, ind)
        n, vt = self.rng.choice(cands)
        # compileSource lowers no store of a struct, enum or array into a field
        scalar = [(f, ft) for f, ft in self.structs[vt] if is_int(ft) or ft == 'bool']
        if not scalar:
            return self.s_emit(s, d, ind)
        f, ft = self.rng.choice(scalar)
        if is_int(ft) and self.chance(0.3):
            op = self.rng.choice(['+', '-', '^', '|'])
            return [ind + f'{n}.{f} {op}= {self.int_expr(s, ft, 1)};']
        return [ind + f'{n}.{f} = {self.expr(s, ft, self.depth)};']

    def s_store(self, s, d, ind):
        cands = [(n, vt) for n, vt in s.vars() if array_parts(vt) and n in self.assignable(s, lambda t: True)]
        if not cands:
            return self.s_emit(s, d, ind)
        n, vt = self.rng.choice(cands)
        et, size = array_parts(vt)
        i = self.index(s, size)
        # Past the end, Core traps before it evaluates the value and laniusc
        # after (the docstring's store order, counted as known), so the front
        # end reads no store whose value calls a function (effActs).
        v = self.lit(et)
        for _ in range(4):
            e = self.expr(s, et, self.depth)
            if not CALL.search(e):
                v = e
                break
        return [ind + f'{n}[{i}] = {v};']

    def s_emit(self, s, d, ind):
        t = self.int_type()
        e = self.int_expr(s, t, self.depth, True)
        if self.chance(0.2):
            return [ind + f'out_err(({e} as u32));']
        return [ind + f'out_hex(({e} as u64));']

    def s_write(self, s, d, ind):
        return [ind + f'std::io::write_byte({self.rng.choice([1, 2])}, {self.int_expr(s, "i32", 1)});']

    def s_if(self, s, d, ind):
        out = [ind + f'if ({self.bool_expr(s, self.depth)}) {{']
        out += self.block(s, self.rng.randrange(1, 4), d - 1, ind + '    ', self.jump_tail(s))
        if self.chance(0.5):
            out.append(ind + '} else {')
            out += self.block(s, self.rng.randrange(1, 3), d - 1, ind + '    ', self.jump_tail(s))
        out.append(ind + '}')
        return out

    def jump_tail(self, s):
        if s.loop and self.chance(0.3):
            return self.rng.choice(['break', 'continue'])
        if s.ret is not None and self.chance(0.1):
            return 'return'
        return None

    def s_early(self, s, d, ind):
        out = [ind + f'if ({self.bool_expr(s, self.depth)}) {{']
        out += self.block(s, self.rng.randrange(0, 2), d - 1, ind + '    ', 'return')
        out.append(ind + '}')
        return out

    def s_jump(self, s, d, ind):
        out = [ind + f'if ({self.bool_expr(s, self.depth)}) {{']
        out += self.block(s, self.rng.randrange(0, 2), d - 1, ind + '    ', self.rng.choice(['break', 'continue']))
        out.append(ind + '}')
        return out

    def s_while(self, s, d, ind):
        c = s.fresh('c')
        n = self.rng.randrange(1, 9)
        ct = self.rng.choice(['i32', 'u32', 'usize', 'i64', 'u8'])
        cond = f'{c} < {n}'
        if self.chance(0.3):
            cond = f'({cond}) && {self.bool_expr(s, 1)}'
        out = [ind + f'let {c}: {ct} = 0;', ind + f'while ({cond}) {{', ind + f'    {c} = {c} + 1;']
        s.loop += 1
        s.mult *= n
        s.bind(c, ct)  # read in the body, never assigned (assignable() leaves out c, i and n names)
        out += self.loop_body(s, d, ind)
        s.mult //= n
        s.loop -= 1
        out.append(ind + '}')
        return out

    def loop_body(self, s, d, ind):
        """A loop's body, often with a break or continue before or after the rest."""
        body = self.block(s, self.rng.randrange(1, 4), d - 1, ind + '    ')
        if d > 0 and self.chance(min(0.8, 0.25 * self.w['loop'])):
            jump = self.s_jump(s, d, ind + '    ')
            body = jump + body if self.chance(0.5) else body + jump
        return body

    def s_for(self, s, d, ind):
        lim, i = s.fresh('n'), s.fresh('i')
        t = self.rng.choice(['i32', 'u32', 'usize', 'i64', 'u8', 'i16'])
        bound = self.int_expr(s, t, 1, True)
        out = [ind + f'let {lim}: {t} = ({bound} & 7);', ind + f'for {i} in {self.rng.choice([0, 0, 1, 2])}..{lim} {{']
        s.loop += 1
        s.mult *= 8
        s.push()
        s.bind(i, t)
        out += self.loop_body(s, d, ind)
        s.pop()
        s.mult //= 8
        s.loop -= 1
        out.append(ind + '}')
        return out

    def s_block(self, s, d, ind):
        return [ind + '{'] + self.block(s, self.rng.randrange(1, 3), d - 1, ind + '    ') + [ind + '}']

    def s_match(self, s, d, ind):
        scr = self.scrutinees(s, 1)
        scr = [(text, t) for text, t in scr if all(len(ps) <= 1 for _, ps in self.variants(t))]
        if not scr:
            return None
        text, st = self.rng.choice(scr)
        out = [ind + f'match ({text}) {{']
        for pat, binders in self.arms(s, st, statement=True):
            s.push()
            for b, bt in binders:
                s.bind(b, bt)
            out.append(ind + f'    {pat} -> {{')
            out += self.block(s, self.rng.randrange(0, 3), d - 1, ind + '        ', 'return')
            out.append(ind + '    },')
            s.pop()
        out.append(ind + '};')
        return out

    def try_callees(self, s):
        """Functions whose result `?` can take here: the same enum as the
        function's, with the same failure payload."""
        if option_of(s.ret):
            return [f for f in self.fns if f.ret and option_of(f.ret) and f.name != s.fn and f.cost * s.mult <= 4000]
        if result_of(s.ret):
            e = result_of(s.ret)[1]
            return [f for f in self.fns if f.ret and result_of(f.ret) and result_of(f.ret)[1] == e
                    and f.name != s.fn and f.cost * s.mult <= 4000]
        return []

    def s_try(self, s, d, ind):
        f = self.rng.choice(self.try_callees(s))
        payload = option_of(f.ret) or result_of(f.ret)[0]
        call = self.call(s, f, 2)
        k = self.rng.randrange(5)
        if k == 0:
            return [ind + f'{call}?;']
        if k == 1:
            names = [n for n in self.assignable(s, lambda t: t == payload)]
            if names:
                return [ind + f'{self.rng.choice(names)} = {call}?;']
        if k == 2:
            r, x = s.fresh(), s.fresh()
            s.bind(r, f.ret)
            s.bind(x, payload)
            return [ind + f'let {r}: {f.ret} = {call};', ind + f'let {x}: {payload} = {r}?;']
        x = s.fresh()
        s.bind(x, payload)
        if k == 3:
            return [ind + f'let {x} = {call}?;']
        return [ind + f'let {x}: {payload} = {call}?;']

    def calls_to_any(self, s):
        return [f for f in self.fns if f.cost * s.mult <= 4000 and f.name != s.fn]

    def s_callstmt(self, s, d, ind):
        return [ind + self.call(s, self.rng.choice(self.calls_to_any(s)), 2) + ';']

    # ------------------------------------------------ items

    def fn_body(self, s, n, d):
        out = self.block_open(s, n, d)
        return out

    def block_open(self, s, n, d):
        out = []
        for _ in range(n):
            out += self.stmt(s, d, '    ')
        if s.ret:
            out += self.returns(s, d, '    ')
        return out

    def returns(self, s, d, ind):
        """A block's last statement, which returns: a return, or a match
        statement whose block arms all return (laniusc requires that)."""
        if d > 0 and s.ret and ind == '    ' and self.chance(0.25 * self.w['match']):
            out = self.s_match(s, d, ind)
            if out:
                return out
        return [ind + f'return {self.ret_value(s)};' if s.ret else ind + 'return;']

    def params(self, n):
        return [(f'a{i}', self.value_type()) for i in range(n)]

    def add_struct(self):
        name = self.name('S')
        fields = []
        for i in range(self.rng.randrange(1, 5) if self.chance(0.8) else self.rng.randrange(5, 9)):
            k = self.rng.random()
            if k < 0.12 and self.structs:
                ft = self.rng.choice(sorted(self.structs))
            elif k < 0.2:
                ft = f'[{self.int_type()}; {self.rng.choice([2, 3, 4])}]'
            elif k < 0.28 and self.enums:
                ft = self.rng.choice(sorted(self.enums))
            else:
                ft = self.scalar_type()
            fields.append((f'q{i}', ft))
        self.structs[name] = fields
        self.items.append(f'struct {name} {{ {", ".join(f"{f}: {t}" for f, t in fields)} }}')

    def add_generic_struct(self):
        """struct W<T> { v: T, n: N } at one or two scalar types, a generic
        function that makes one and one that reads it."""
        name, mk, get = self.name('W'), self.name('gm'), self.name('gr')
        nt = self.int_type()
        self.items.append(f'struct {name}<T> {{ v: T, n: {nt} }}')
        xs = sorted({self.scalar_type() for _ in range(self.rng.randrange(1, 3))})
        self.items.append(f'fn {mk}<T>(v: T, n: {nt}) -> {name}<T> {{\n    return {name} {{ v: v, n: n }};\n}}')
        self.items.append(f'fn {get}<T>(w: {name}<T>, k: i32) -> T {{\n'
                          f'    if ((w.n as i32) > k) {{\n        out_hex((w.n as u64));\n    }}\n'
                          f'    let x: T = w.v;\n    return x;\n}}')
        for x in xs:
            inst = f'{name}<{x}>'
            self.structs[inst] = [('v', x), ('n', nt)]
            self.fns.append(Fn(mk, [('v', 'T'), ('n', nt)], inst, 'generic', cost=1, generic=(None, [x])))
            self.fns.append(Fn(get, [('w', inst), ('k', 'i32')], x, 'generic', cost=2, generic=(None, [x])))

    def payload_type(self):
        """A variant's payload: mostly a scalar, else a struct, an earlier
        enum or an Option or Result, so that patterns nest."""
        k = self.pick([(8, 'scalar'), (1 if self.structs else 0, 'struct'),
                       (1.5 * self.w['nest'] if self.enums else 0, 'enum'), (0.5 * self.w['nest'], 'option'),
                       (0.3 * self.w['nest'], 'result')])
        if k == 'struct':
            return self.rng.choice(sorted(self.structs))
        if k == 'enum':
            return self.rng.choice(sorted(self.enums))
        if k == 'option':
            return f'{OPTION}{self.scalar_type()}>'
        if k == 'result':
            return f'{RESULT}{self.scalar_type()}, {self.err}>'
        return self.scalar_type()

    def add_enum(self):
        name = self.name('E')
        vs = []
        for i in range(self.rng.randrange(2, 5)):
            n = self.rng.choice([0, 0, 1, 1, 1, 2])
            ps = [self.payload_type() for _ in range(n)]
            vs.append((self.name('V'), ps))
        self.enums[name] = vs
        self.items.append(f'enum {name} {{ ' + ', '.join(f'{v}({", ".join(ps)})' if ps else v for v, ps in vs)
                          + ' }')

    def add_const(self):
        t = self.int_type() if self.chance(0.85) else 'bool'
        name = self.name('K')
        self.consts[name] = t
        # no parentheses: the front end reads `(-k)` as a constant's value only for a narrow k
        self.items.append(f'const {name}: {t} = {self.lit(t).strip("()")};')

    def add_fn(self, kind='plain'):
        name = self.name('f')
        ret = self.value_type()
        if kind == 'try':
            ret = self.rng.choice([f'{OPTION}{self.value_type(0)}>', f'{RESULT}{self.value_type(0)}, {self.err}>'])
        params = self.params(self.rng.randrange(0, 4) if self.chance(0.8) else self.rng.randrange(4, 10))
        if kind == 'rec':
            params = [('a0', 'i32')] + [(f'a{i + 1}', t) for i, (_, t) in enumerate(params[:2])]
        unit = kind == 'plain' and self.chance(0.12)
        f = Fn(name, params, None if unit else ret, kind)
        s = Scope(name, f.ret)
        for p, t in params:
            s.bind(p, t)
        n = self.rng.randrange(2, 7)
        body = []
        if kind == 'rec':
            # the base case, then the body, then the recursive call
            body.append(f'    if (a0 <= 0) {{')
            body.append(f'        return {self.expr(s, ret, self.depth)};')
            body.append('    }')
            f.cost = 16
            self.fns.append(f)  # visible to itself, for its own call
            s.mult = 16
            for _ in range(self.rng.randrange(1, 4)):
                body += self.stmt(s, 1, '    ')
            args = ', '.join(['(a0 - 1)'] + [self.expr(s, pt, 1) for _, pt in params[1:]])
            if is_int(ret) and self.chance(0.5):
                body.append(f'    return ({self.int_expr(s, ret, 1)} {self.rng.choice(["+", "^", "-"])} '
                            f'{name}({args}));')
            else:
                r = s.fresh()
                body.append(f'    let {r}: {ret} = {name}({args});')
                s.bind(r, ret)
                body.append(f'    return {self.expr(s, ret, 1)};')
            self.fns.remove(f)
        else:
            s.mult = 1
            body = self.block_open(s, n, 2)
        f.cost = max(1, self.estimate(body)) * (16 if kind == 'rec' else 1)
        self.fns.append(f)
        ps = ', '.join(f'{p}: {t}' for p, t in params)
        self.items.append(f'fn {name}({ps})' + (f' -> {f.ret}' if f.ret else '') + ' {\n' + '\n'.join(body) + '\n}')

    def estimate(self, lines):
        """A rough cost of running lines: the calls they make, loops multiplying."""
        cost, depth, loops = 1, 0, [(-1, 1)]
        for line in lines:
            st = line.strip()
            if st.startswith('}'):
                depth -= 1
                while depth <= loops[-1][0]:
                    loops.pop()
            mult = loops[-1][1]
            for g in self.fns:
                if re.search(rf'\b{g.name}\(', st):
                    cost += g.cost * mult
            cost += mult
            if st.endswith('{'):
                m = re.match(r'while \(\w+ < (\d+)\)', st)
                if m or st.startswith('for '):
                    loops.append((depth, mult * (int(m.group(1)) if m else 8)))
                depth += 1
        return min(cost, 1 << 20)

    def add_trait(self):
        name = self.name('T')
        method = self.name('m')
        self_form = self.chance(0.5)
        ret = self.int_type() if self.chance(0.85) else 'bool'
        impl_types = []
        pool = INT_NAMES + [x for x in sorted(self.structs) if '<' not in x] + ['bool']
        for x in self.rng.sample(pool, min(len(pool), self.rng.randrange(1, 4))):
            impl_types.append(x)
        sig = f'fn {method}(self, k: i32) -> {ret};' if self_form else f'fn {method}(v: T) -> {ret};'
        self.items.append(f'trait {name}<T> {{\n    {sig}\n}}')
        for x in impl_types:
            s = Scope(method, ret)
            v = 'self' if self_form else 'v'
            s.bind(v, x)
            if self_form:
                s.bind('k', 'i32')
            body = self.block_open(s, self.rng.randrange(0, 3), 1)
            head = f'fn {method}(self, k: i32) -> {ret}' if self_form else f'fn {method}(v: {x}) -> {ret}'
            self.items.append(f'impl {name}<{x}> for {x} {{\n    {head} {{\n' +
                              '\n'.join('    ' + b for b in body) + '\n    }\n}')
        self.traits[name] = dict(method=method, self_form=self_form, ret=ret, impls=impl_types)
        # A generic function bounded by the trait, by a bound or a where clause.
        g = self.name('g')
        gret = self.int_type()
        s = Scope(g, gret)
        s.self_type = ('T', name)
        s.bind('x', 'T')
        s.bind('a1', 'i32')
        call = f'x.{method}(a1)' if self_form else f'T::{method}(x)'
        body = [f'    let r: {ret} = {call};']
        s.bind('r', ret)
        body += self.block_open(s, self.rng.randrange(1, 3), 1)
        if self.chance(0.5):
            head = f'fn {g}<T: {name}<T> >(x: T, a1: i32) -> {gret}'
        else:
            head = f'fn {g}<T>(x: T, a1: i32) -> {gret} where T: {name}<T>'
        self.items.append(head + ' {\n' + '\n'.join(body) + '\n}')
        self.fns.append(Fn(g, [('x', 'T'), ('a1', 'i32')], gret, 'generic', cost=4, generic=(name, impl_types)))

    def add_methods(self):
        """An inherent impl on a struct or an enum: methods taking self
        (called x.m(..)) and associated functions (called S::m(..))."""
        owners = [x for x in sorted(self.structs) if '<' not in x] + sorted(self.enums)
        if not owners:
            return
        st = self.rng.choice(owners)
        ms = []
        lines = [f'impl {st} {{']
        for _ in range(self.rng.randrange(1, 3)):
            m = self.name('h')
            ret = self.value_type(0)
            with_self = self.chance(0.6)
            params = [('self' if with_self else 'a0', st)] + \
                [(f'a{i + 1}', self.value_type(0)) for i in range(self.rng.randrange(0, 3))]
            s = Scope(m, ret)
            for p, t in params:
                s.bind(p, t)
            body = self.block_open(s, self.rng.randrange(1, 4), 1)
            ps = ', '.join('self' if p == 'self' else f'{p}: {t}' for p, t in params)
            lines.append(f'    fn {m}({ps}) -> {ret} {{')
            lines += ['    ' + b for b in body]
            lines.append('    }')
            f = Fn(m, params, ret, 'method' if with_self else 'static', cost=max(1, self.estimate(body)))
            ms.append(f)
        lines.append('}')
        self.items.append('\n'.join(lines))
        self.methods.setdefault(st, []).extend(ms)

    def program(self):
        rng = self.rng
        for _ in range(rng.randrange(0, 3)):
            self.add_const()
        for _ in range(rng.randrange(0, 3)):
            self.add_struct()
        for _ in range(rng.randrange(0, 3)):
            self.add_enum()
        if self.chance(0.4):
            self.add_struct()
        if self.chance(0.4):
            self.add_generic_struct()
        plan = ['plain'] * rng.randrange(1, 4) + ['try'] * (rng.randrange(0, 3) if self.w['try'] >= 1 else 0) + \
            ['rec'] * (rng.randrange(0, 3) if self.w['rec'] >= 1 else 0) + \
            ['trait'] * (rng.randrange(0, 3) if self.w['trait'] >= 1 else 0) + ['methods'] * rng.randrange(0, 2)
        rng.shuffle(plan)
        for k in plan:
            if k == 'trait':
                self.add_trait()
            elif k == 'methods':
                self.add_methods()
            else:
                self.add_fn(k)
        if self.w['try'] >= 1:
            self.add_fn('try')
        # main
        s = Scope('main', 'i32')
        body = []
        for _ in range(rng.randrange(2, 5)):
            t = self.int_type()
            n = s.fresh()
            body.append(f'    let {n}: {t} = {self.lit(t)};')
            s.bind(n, t)
        for _ in range(rng.randrange(5, 12)):
            body += self.stmt(s, 2, '    ')
        for n, t in s.vars():
            if is_int(t) and self.chance(0.5):
                body.append(f'    out_hex(({n} as u64));')
        body.append(f'    return {self.int_expr(s, "i32", 2)};')
        items = self.items + [OUT_HEX.rstrip('\n'), 'fn main() -> i32 {\n' + '\n'.join(body) + '\n}']
        return 'module app::main;\n\n' + ''.join(f'import {m};\n' for m in IMPORTS) + '\n' + \
            '\n\n'.join(items) + '\n'


def generate(seed, k):
    return Gen(random.Random(f'{seed}:{k}')).program()


# ---------------------------------------------------------------- parse trees, on the CPU

class Parser:
    """Parse trees in laniusc's form (each nonterminal node's production id,
    in preorder, and its parent), found on the CPU: the verified validator
    checks every tree, so this parser is not trusted, as laniusc's is not.

    The tokens are the Lean lexer's (runAll `dump`), with canonical kinds;
    the grammar's terminals are laniusc's contextual kinds, each standing for
    its canonical kind (grammar_table.py's mapping), and its LL(1) table
    (tables/parse_tables.meta.json) is keyed by contextual kinds. So a
    nonterminal may have several productions for one canonical lookahead;
    they are tried in turn, backtracking, as is a `>` that takes the first
    half of a `>>` (the validator's one exception to a token a terminal)."""

    def __init__(self):
        import json
        import grammar_table as gt
        meta = json.load(open(gt.META))
        codes, canonical = gt.token_codes(), gt.canonical_map()
        canonical['MatchArrow'] = 'Arrow'

        def code(name):
            return -1 if name == '$' else codes[canonical.get(name, name)]
        self.rhs = [[x if x in {q['lhs'] for q in meta['productions']} else code(x.strip("'"))
                     for x in p['rhs']] for p in meta['productions']]
        self.lhs = [p['lhs'] for p in meta['productions']]
        self.pred = {}
        for row in meta['ll1_predictions']:
            cands = self.pred.setdefault((row['nonterminal'], code(row['lookahead'])), [])
            if row['production'] not in cands:
                cands.append(row['production'])
        self.gt, self.shr = codes['Gt'], codes['Shr']
        self.start = meta['start']
        self.code = codes
        # The validator's one reading (frontend.lani's picks): the production
        # ids it names, by its functions' names.
        front = open(os.path.join(run_cache.ROOT, 'formal/lani/mini/frontend.lani')).read()

        def prod(name):
            return int(re.search(r'fn %s\(\) -> usize \{\s*return (\d+);' % name, front).group(1))
        self.p_member_args, self.p_block, self.p_expr_stmt, self.p_ident, self.p_ident_args = (
            prod(n) for n in ('p_member_type_args_some', 'p_block_stmt', 'p_expr_stmt',
                              'p_path_ident', 'p_path_ident_args'))

    def tokens(self, dump_line):
        """The token kinds of one `file` line of runAll's dump."""
        toks = dump_line.split(' file ', 1)[1].split('|')[0].split()
        return [int(t.split(':')[0]) for t in toks]

    def generic_path_at(self, at, m):
        """frontend.lani's generic_path_at over the tokens at(0), ..., at(m - 1)."""
        c = self.code
        stop = {c['OrOr'], c['EqEq'], c['NotEqual'], c['Le'], c['Ge']}
        opens, closes = {c['LParen'], c['LBracket'], c['LBrace']}, {c['RParen'], c['RBracket'], c['RBrace']}

        def tail(j):
            return j < m and (at(j) in (c['LParen'], c['LBrace']) or
                              (at(j) == c['Colon'] and j + 1 < m and at(j + 1) == c['Colon']))
        if m < 2 or at(1) != c['Lt']:
            return False
        j, angles, nest = 2, 1, 0
        while j < m:
            k = at(j)
            j += 1
            if k in stop:
                return False
            if k in opens:
                nest += 1
            elif k in closes:
                if nest == 0:
                    return False
                nest -= 1
            elif nest:
                continue
            elif k == c['Semicolon']:
                return False
            elif k == c['Lt']:
                angles += 1
            elif k == self.gt:
                if angles < 2:
                    return tail(j)
                angles -= 1
            elif k == self.shr:
                if angles == 2:
                    return tail(j)
                if angles < 2:
                    return False
                angles -= 2
        return False

    def picks(self, p, kinds, pos):
        """frontend.lani's picks: whether the validator accepts production p
        for a node whose tokens begin at pos."""
        if p not in (self.p_member_args, self.p_block, self.p_expr_stmt, self.p_ident, self.p_ident_args):
            return True
        i, half = pos

        def at(j):
            return self.gt if half and j == 0 else kinds[i + j]
        m = len(kinds) - i
        if p == self.p_member_args:
            return False
        if p in (self.p_block, self.p_expr_stmt):
            return (m > 0 and at(0) == self.code['LBrace']) == (p == self.p_block)
        return self.generic_path_at(at, m) == (p == self.p_ident_args)

    def parse(self, kinds):
        """(prods, parents) of the file with these token kinds, or None.

        A leftmost derivation with an explicit stack: its expansions come in
        preorder, so each is the next (production, parent) of the tree. A
        choice point (several productions for a lookahead) keeps the rest of
        its alternatives with the stack (a linked list, so shared), the
        position and the tree's length to go back to."""
        n, gt, shr, pred, rhs = len(kinds), self.gt, self.shr, self.pred, self.rhs
        prods, parents, choices = [], [], []
        stack, pos = ((self.start, 4294967295), None), (0, 0)

        def expand(p, up, rest):
            me = len(prods)
            prods.append(p)
            parents.append(up)
            for x in reversed(rhs[p]):
                rest = ((x, me) if isinstance(x, str) else x, rest)
            return rest

        while True:
            if stack is None:
                if pos == (n, 0):
                    return prods, parents
                ok = False
            else:
                top, rest = stack
                i, half = pos
                ok = True
                if isinstance(top, int):
                    if half:
                        ok = top == gt
                        pos = (i + 1, 0)
                    elif i < n and kinds[i] == top:
                        pos = (i + 1, 0)
                    elif i < n and top == gt and kinds[i] == shr:
                        pos = (i, 1)
                    else:
                        ok = False
                    stack = rest
                else:
                    name, up = top
                    cands = []
                    for k in ([gt] if half else [-1] if i >= n else [kinds[i], gt] if kinds[i] == shr else [kinds[i]]):
                        for p in pred.get((name, k), ()):
                            if p not in cands and self.picks(p, kinds, pos):
                                cands.append(p)
                    if not cands:
                        ok = False
                    else:
                        if len(cands) > 1:
                            choices.append([cands, 1, stack, pos, len(prods)])
                        stack = expand(cands[0], up, rest)
            if ok:
                continue
            while choices and choices[-1][1] >= len(choices[-1][0]):
                choices.pop()
            if not choices:
                return None
            c = choices[-1]
            cands, j, stack, pos, size = c
            c[1] = j + 1
            del prods[size:], parents[size:]
            (name, up), rest = stack
            stack = expand(cands[j], up, rest)


# ---------------------------------------------------------------- the verified compiler

class Verified:
    """The verified compiler's side: parse trees (Parser, no GPU), the
    validator, runAll's ELF executables."""

    def __init__(self, args, workdir):
        self.args, self.workdir = args, workdir
        self.panics = []
        self.files = os.path.join(workdir, 'files')
        os.makedirs(self.files, exist_ok=True)
        self.parser = Parser()
        mods = so.load_modules()
        reach = dict(mods)
        reach['app::main'] = types.SimpleNamespace(imports=IMPORTS, paths=set())
        self.deps = []
        for d in so.closure(reach, 'app::main')[1:]:
            base = os.path.join(self.files, d.replace('::', '__'))
            shutil.copy(mods[d].path, base + '.lani')
            self.deps.append(base)
        self.trees(self.deps)
        bad = set(self.deps) - so.validate_all(self.deps, workdir)
        if bad:
            raise SystemExit(f'the validator rejects the parse trees of {sorted(bad)}')

    def trees(self, bases):
        """Write each base's parse tree (cached by its text); the bases with none."""
        none, todo = [], []
        for b in bases:
            text = open(b + '.lani', 'rb').read()
            # Keyed by the tables, this parser and the validator's picks.
            k = run_cache.key('fuzz-parse', run_cache.file_digest(os.path.join(run_cache.ROOT, 'tables',
                                                                               'parse_tables.meta.json')),
                              run_cache.file_digest(os.path.abspath(__file__)),
                              run_cache.file_digest(os.path.join(run_cache.ROOT, 'formal/lani/mini/frontend.lani')),
                              text)
            hit = run_cache.load('cpu-parse', k)
            if hit is not None:
                so.write_tree(b, (hit['prods'], hit['parents']))
            else:
                todo.append((b, k))
                so.write_tree(b, ([], []))
        if todo:
            manifest = os.path.join(self.workdir, 'dump.txt')
            open(manifest, 'w').write(''.join(f'dump d{i} {b}\n' for i, (b, _) in enumerate(todo)))
            run = subprocess.run([so.RUN_ALL, manifest], capture_output=True, text=True, timeout=240)
            self.note_panics(run)
            out = run.stdout
            lines = {line.split(' ', 1)[0]: line for line in out.split('\n') if ' file ' in line}
            for i, (b, k) in enumerate(todo):
                tree = self.parser.parse(self.parser.tokens(lines[f'd{i}'])) if f'd{i}' in lines else None
                if tree is None:
                    none.append(b)
                    continue
                so.write_tree(b, tree)
                run_cache.store('cpu-parse', k, dict(prods=tree[0], parents=tree[1]))
        return none

    def note_panics(self, run):
        """Keep the PANIC lines a runAll run wrote: a Lean panic prints one
        and the run goes on with a default value."""
        self.panics += [line.strip() for line in run.stderr.split('\n') if 'PANIC' in line]

    def compile(self, texts, tag):
        """For each text, ('elf', path), ('panic', the PANIC line) or (status, reason)."""
        self.panics = []
        out = self.compile_batch(texts, tag)
        if self.panics:
            if len(texts) == 1:
                out = [('panic', self.panics[0])]
            else:
                # which: each alone (rare)
                out = [o if self.compile([t], f'{tag}{k}s')[0][0] != 'panic' else ('panic', self.panics[0])
                       for k, (t, o) in enumerate(zip(texts, out))]
        return out

    def compile_batch(self, texts, tag):
        out = [None] * len(texts)
        bases = [os.path.join(self.workdir, f'{tag}{k}') for k in range(len(texts))]
        for b, text in zip(bases, texts):
            open(b + '.lani', 'w').write(text)
            if os.path.exists(b + '.elf'):
                os.remove(b + '.elf')
        none = set(self.trees(bases))
        good = so.validate_all(bases, self.workdir)
        lines = []
        for k, (b, text) in enumerate(zip(bases, texts)):
            if b in none or b not in good:
                out[k] = ('noparse', 'no parse tree' if b in none else 'the validator rejects the parse tree')
                continue
            entry = po.entry_index(text)
            lines.append(f'elf {tag}{k} {b}.elf {entry} {16 * MIB} {64 * MIB} {b} ' + ' '.join(self.deps))
        manifest = os.path.join(self.workdir, f'{tag}manifest.txt')
        open(manifest, 'w').write('\n'.join(lines) + '\n')
        run = subprocess.run([so.RUN_ALL, manifest], capture_output=True, text=True, timeout=240)
        self.note_panics(run)
        said = dict(line.split(' ', 1) for line in run.stdout.strip().split('\n') if ' ' in line)
        for k, b in enumerate(bases):
            if out[k] is not None:
                continue
            status = said.get(f'{tag}{k}', 'missing').split(' ')[0]
            if status == 'elf' and os.path.exists(b + '.elf'):
                os.chmod(b + '.elf', 0o755)
                out[k] = ('elf', b + '.elf')
            else:
                out[k] = (status, None)
        return out

    def why(self, base):
        return so.why([base] + self.deps, self.workdir, os.path.basename(base))


