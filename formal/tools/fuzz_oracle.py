LCC = 'target/claude-work/bin/lcc'


def lcc_laniusc():
    """The laniusc binary behind lcc's daemon (the main checkout's), else this checkout's."""
    try:
        text = open(LCC).read()
        home = re.search(r"^HOME = '([^']+)'", text, re.M).group(1)
        return home + re.search(r"^LANIUSC = HOME \+ '([^']+)'", text, re.M).group(1)
    except (OSError, AttributeError):
        return 'target/release/laniusc'


def gap(reason):
    """A short class of srcDump's reason (stdlib_oracle.gap's patterns
    would take `x & 63` for a reference)."""
    if reason.startswith('compileSource: '):
        return so.gap(reason)
    return re.sub(r'\b[a-z]\d+\b', 'x', reason.split(': ', 1)[-1])[:60]


def error_text(out):
    """laniusc's diagnostic as one line (lcc passes the daemon's JSON on)."""
    import json
    try:
        d = json.loads(out.strip().split('\n')[-1])
        label = d.get('primary_label') or {}
        notes = '; '.join(n for n in d.get('notes') or [] if isinstance(n, str))
        return (f'{d.get("code")} {d.get("message")}: {label.get("message", "")} at line {label.get("line")}: '
                f'{label.get("source_line", "").strip()}' + (f' (notes: {notes})' if notes else ''))
    except (ValueError, AttributeError):
        return out[-3000:]


class Laniusc:
    """laniusc's side: each program built alone through lcc, the resident
    compiler (one GPU job at a time, under heavy's lock), cached as
    stdlib_oracle.build caches."""

    def __init__(self, args, workdir):
        self.args, self.workdir = args, workdir
        self.builds = 0
        self.build_s = 0.0

    def build(self, name, text, stop=None):
        """The binary, or None and laniusc's error (None and None when the
        compile is still waiting, mostly for the shared GPU, at stop)."""
        # laniusc loads its kernels from its shader artifacts, so a shader-only
        # change can leave the binary as it was (gate.py keys on both).
        k = run_cache.key(run_cache.file_digest(self.args.laniusc), run_cache.tree_digest(
            os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(self.args.laniusc)))),
                         'shaders')),
                          run_cache.tree_digest(so.STDLIB), text)
        hit = run_cache.load_file('build', k)
        if hit is not None:
            return hit, ''
        began = time.time()
        lani = os.path.join(self.workdir, name + '.lani')
        exe = os.path.join(self.workdir, name)
        open(lani, 'w').write(text)
        if os.path.exists(exe):
            os.remove(exe)
        wait = 120 if stop is None else max(1.0, min(120, stop - time.time()))
        try:
            run = subprocess.run([LCC, '--stdlib-root', so.STDLIB, '-o', exe, lani], capture_output=True,
                                 text=True, timeout=wait)
        except subprocess.TimeoutExpired:
            self.build_s += time.time() - began
            return None, None
        self.builds += 1
        self.build_s += time.time() - began
        if run.returncode != 0 or not os.path.exists(exe):
            return None, error_text(run.stdout + run.stderr)
        return run_cache.store_file('build', k, exe), ''

    def outcomes(self, texts, tag, stop=None):
        """Each program's laniusc outcome: ('ran', (status, stdout, stderr)),
        ('rejects', error), or ('skipped', '') once the clock passes stop."""
        out = []
        for k, text in enumerate(texts):
            if stop is not None and time.time() > stop:
                out.append(('skipped', ''))
                continue
            exe, error = self.build(f'{tag}{k}', text, stop)
            if exe is None and error is None:
                stop = time.time()  # the GPU is busy past the budget: skip the rest
                out.append(('skipped', ''))
                continue
            out.append(('rejects', error) if exe is None else ('ran', po.run([exe])))
        return out


# ---------------------------------------------------------------- comparing

def agree(want, have):
    if want == have:
        return True
    if want[0] == 'timeout' and have[0] == 'timeout':
        return True
    return want[0] in po.VERIFIED_TRAPS and have[0] in po.LANIUSC_TRAPS and want[1:] == have[1:]


# laniusc rejections that are a known difference from Core, not a fault of
# either compiler: laniusc evaluates constant operands at compile time and
# rejects a program whose constant operation would trap, where Core (and so
# the verified compiler) compiles it and traps when it runs there. Such
# programs are counted as known, neither agreeing nor disagreeing.
KNOWN_REJECTS = [
    ('unsupported x86 zero divisor', 'laniusc rejecting a constant divisor of zero (KNOWN_REJECTS)'),
    ('unsupported x86 array index bounds', 'laniusc rejecting a constant index past the end of an array (KNOWN_REJECTS)'),
]


def known_reject(error):
    for text, what in KNOWN_REJECTS:
        if text in error:
            return what
    return None


STORE_ORDER = 'an out-of-bounds store whose value laniusc evaluates first (store_order_known)'
INDEXED_STORE = re.compile(r'\]\s*=[^=]')


def store_order_known(text, want, have):
    """Whether two runs differ only as the store order would make them
    (SEMANTIC_DECISIONS.md, "Traps in compiled code"): both trap, the
    program stores through an index, and the verified compiler's output is
    where laniusc's starts (laniusc evaluated the value first, then trapped,
    perhaps at a trap of the value's own)."""
    return (want[0] in po.VERIFIED_TRAPS and have[0] in po.LANIUSC_TRAPS and
            INDEXED_STORE.search(text) is not None and
            have[1].startswith(want[1]) and have[2].startswith(want[2]))


def verdict(v, l, text):
    """How the two compilers' outcomes compare: None when they agree or
    either does not compile it, ('known', what) for a known difference,
    else a short kind."""
    if v[0] == 'panic':
        # Lean's panic message, without the source position that names it
        return 'the verified compiler panics: ' + re.sub(r'\d+:\d+', '', v[1])[:160]
    if v[0] != 'elf' or l[0] == 'skipped':
        return None
    if l[0] == 'rejects' and 'panicked at' in l[1]:
        return 'laniusc panics: ' + l[1][l[1].index('panicked at'):][:160]
    if l[0] == 'rejects':
        what = known_reject(l[1])
        if what:
            return ('known', what)
        # The diagnostic without its place, so that minimizing keeps it.
        return ('laniusc fails' if 'LNC0057' in l[1] else 'laniusc rejects') + \
            ': ' + l[1].split(' at line ')[0][:200]
    want = po.run([v[1]])
    if agree(want, l[1]):
        return None
    return ('known', STORE_ORDER) if store_order_known(text, want, l[1]) else 'differ'


def vrun(v):
    """The verified compiler's run of an outcome: its ELF's, or its panic as stderr."""
    return po.run([v[1]]) if v[0] == 'elf' else ('panic', b'', v[1].encode())


def shown(r):
    code, out, err = r
    return f'exit {code}, stdout {out[:200]!r}, stderr {err[:120]!r}'


def evaluate(verified, laniusc, texts, tag):
    """(verified outcome, laniusc outcome, kind) for each text."""
    vs = verified.compile(texts, tag)
    ok = [k for k, v in enumerate(vs) if v[0] in ('elf', 'panic')]
    ls = laniusc.outcomes([texts[k] for k in ok], tag + 'l')
    lout = [None] * len(texts)
    for k, l in zip(ok, ls):
        lout[k] = l
    return [(v, l, verdict(v, l, t) if l else None) for v, l, t in zip(vs, lout, texts)]


# ---------------------------------------------------------------- minimizing

def units(lines, lo, hi):
    """The units of lines[lo:hi]: (start, end, children) for a line, or for a
    line opening a block together with its body and closing line."""
    out, i = [], lo
    while i < hi:
        if lines[i].rstrip().endswith('{'):
            depth, j, kids = 1, i + 1, []
            seg = i + 1
            while j < hi and depth:
                st = lines[j].strip()
                if st.startswith('}') and st.endswith('{'):
                    if depth == 1:
                        kids += units(lines, seg, j)
                        seg = j + 1
                elif st.startswith('}'):
                    depth -= 1
                    if depth == 0:
                        kids += units(lines, seg, j)
                        break
                elif st.endswith('{'):
                    depth += 1
                j += 1
            out.append((i, j + 1, kids))
            i = j + 1
        else:
            out.append((i, i + 1, []))
            i += 1
    return out


def without(lines, removed):
    drop = set()
    for a, b in removed:
        drop |= set(range(a, b))
    return [line for k, line in enumerate(lines) if k not in drop]


class Minimizer:
    def __init__(self, verified, laniusc, kind, deadline, save=None):
        self.verified, self.laniusc, self.kind, self.deadline = verified, laniusc, kind, deadline
        self.save = save  # called with each smaller program found
        self.outcome = {}  # a disagreeing text: (verified, laniusc, the verified run)
        self.rounds = 0
        self.last = 0.0
        self.tests = 0

    def more(self):
        """Whether another round fits before the deadline (a round takes
        about as long as the last one: mostly a wait for the GPU)."""
        return time.time() + 1.5 * self.last < self.deadline

    def interesting(self, texts):
        """Whether each text disagrees as the program does (its outcomes kept by text)."""
        began = time.time()
        self.rounds += 1
        self.tests += len(texts)
        rs = evaluate(self.verified, self.laniusc, texts, f'm{self.rounds}_')
        # A program needs its main: without one, runAll is given no entry
        # (a harness artifact, not the verified compiler's output).
        keep = [r[2] == self.kind and 'fn main(' in text for text, r in zip(texts, rs)]
        for text, r, k in zip(texts, rs, keep):
            if k:
                self.outcome[text] = (r[0], r[1], vrun(r[0]))
        self.last = time.time() - began
        return keep

    def run(self, text):
        """The smallest program found by removing units, depth by depth (top
        level items, then their statements, then those in their blocks),
        again from the top while anything changes, until the deadline."""
        lines = [line for line in text.split('\n') if line.strip()]
        changed = True
        while changed and self.more():
            changed = False
            depth = 0
            while self.more():
                level = self.level(lines, depth)
                if not level:
                    break
                while level and self.more():
                    new = self.reduce(lines, level)
                    if new is None:
                        break
                    lines, changed = new, True
                    if self.save:
                        self.save('\n'.join(lines) + '\n')
                    level = self.level(lines, depth)
                depth += 1
        self.complete = not changed and self.more()
        return '\n'.join(lines) + '\n'

    @staticmethod
    def pretty(text):
        """text with a blank line before each item, as generated."""
        out = []
        for line in text.split('\n'):
            if out and line[:1].isalpha() and not line.startswith('import '):
                out.append('')
            out.append(line)
        return '\n'.join(out)

    @staticmethod
    def level(lines, depth):
        us = [u for u in units(lines, 0, len(lines)) if not lines[u[0]].startswith(('module ', 'import '))]
        for _ in range(depth):
            us = [k for _, _, kids in us for k in kids]
        return [(a, b) for a, b, _ in us]

    def reduce(self, lines, spans):
        """One step at a level: the lines with interesting removals made, or
        None. A compile round costs a GPU parse, whatever its size, so a round
        tries every unit's removal at once (units grouped when there are
        more than MAX_CANDIDATES), and a second round the unions of the
        interesting ones, keeping the largest union that still disagrees."""
        n = min(len(spans), MAX_CANDIDATES)
        size = -(-len(spans) // n)
        groups = [spans[i:i + size] for i in range(0, len(spans), size)]
        flags = self.interesting(['\n'.join(without(lines, g)) + '\n' for g in groups])
        hits = [g for g, ok in zip(groups, flags) if ok]
        if not hits:
            return None
        best = hits[0]
        if len(hits) > 1 and self.more():
            unions = [[x for g in hits[:j] for x in g] for j in range(2, len(hits) + 1)]
            flags = self.interesting(['\n'.join(without(lines, u)) + '\n' for u in unions])
            for u, ok in zip(unions, flags):
                if ok:
                    best = u
        return without(lines, best)


