#!/usr/bin/env python3
"""Byte-text constants for a Lanius file of the extracted subset, which has no
string literals.

    python3 formal/tools/text_consts.py formal/lani/mini/extract.lani
    python3 formal/tools/text_consts.py --check formal/lani/mini/extract.lani

Each comment line `// text NAME "..."` (the text a JSON string, so `\\n` and
non-ASCII characters can be written) gets a function `tx_NAME() -> List<usize>`
returning the text's UTF-8 bytes, written between the lines
`// text constants begin` and `// text constants end`. A long text is the
concatenation of pieces of at most 16 bytes, joined as a balanced tree, so no
term nests deeply. With --check, fails if the section is stale.
"""

import json
import re
import sys

BEGIN = '// text constants begin'
END = '// text constants end'
PIECE = 16


def cons_chain(data):
    expr = f'single({data[-1]})'
    for b in reversed(data[:-1]):
        expr = f'cons({b}, {expr})'
    return expr


def joined(names):
    if len(names) == 1:
        return f'{names[0]}()'
    half = len(names) // 2
    return f'concat({joined(names[:half])}, {joined(names[half:])})'


def section(text):
    table = []
    for m in re.finditer(r'^// text ([a-z0-9_]+) (".*")$', text, re.M):
        name, value = m.group(1), json.loads(m.group(2))
        if any(n == name for n, _ in table):
            raise SystemExit(f'text {name} is defined twice')
        if not value:
            raise SystemExit(f'text {name} is empty')
        table.append((name, value.encode()))
    out = [BEGIN, '// Generated by formal/tools/text_consts.py from the `// text` lines; do not edit.', '']
    for name, data in table:
        pieces = [data[i:i + PIECE] for i in range(0, len(data), PIECE)]
        if len(pieces) == 1:
            out += [f'pub fn tx_{name}() -> List<usize> {{',
                    f'    let t: List<usize> = {cons_chain(list(data))};', '    return t;', '}', '']
            continue
        names = [f'tx_{name}_{k}' for k in range(len(pieces))]
        for n, piece in zip(names, pieces):
            out += [f'pub fn {n}() -> List<usize> {{',
                    f'    let t: List<usize> = {cons_chain(list(piece))};', '    return t;', '}', '']
        out += [f'pub fn tx_{name}() -> List<usize> {{',
                f'    let t: List<usize> = {joined(names)};', '    return t;', '}', '']
    out.append(END)
    return '\n'.join(out)


def main(argv):
    check = '--check' in argv
    paths = [a for a in argv if a != '--check']
    if len(paths) != 1:
        print(__doc__.split('\n\n')[0], file=sys.stderr)
        return 2
    path = paths[0]
    text = open(path).read()
    if text.count(BEGIN + '\n') != 1 or text.count(END + '\n') != 1:
        raise SystemExit(f'{path}: needs one `{BEGIN}` and one `{END}` line')
    head, rest = text.split(BEGIN + '\n', 1)
    _, tail = rest.split(END + '\n', 1)
    new = head + section(text) + '\n' + tail
    if check:
        if new != text:
            print(f'{path}: text constants are stale; rerun formal/tools/text_consts.py', file=sys.stderr)
            return 1
        return 0
    if new != text:
        open(path, 'w').write(new)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
