#!/usr/bin/env python3
"""Transform checked, vendored Unicode 17 sentence properties into Lanius ranges.

Only build-time data transformation; production segmentation is Lanius.
No host Unicode database or segmentation library is used.
"""
from __future__ import annotations

import argparse
import gzip
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SB = dict(Other=0, CR=1, LF=2, Extend=3, Format=4, Sep=5, Sp=6,
          Lower=7, Upper=8, OLetter=9, Numeric=10, ATerm=11, STerm=12,
          Close=13, SContinue=14)


def read(root: Path, name: str) -> str:
    manifest = json.loads((root / "sentences-manifest.json").read_text())
    assert manifest["unicode_version"] == "17.0.0"
    entry = next(item for item in manifest["files"] if item["file"] == "sentences-" + name + ".gz")
    compressed = (root / entry["file"]).read_bytes()
    assert hashlib.sha256(compressed).hexdigest() == entry["gzip_sha256"]
    original = gzip.decompress(compressed)
    assert len(original) == entry["bytes"]
    assert hashlib.sha256(original).hexdigest() == entry["sha256"]
    return original.decode("utf-8")


def records(text: str):
    for line in text.splitlines():
        body = line.split("#", 1)[0].strip()
        if not body:
            continue
        fields = [part.strip() for part in body.split(";")]
        span = fields[0].split("..")
        yield int(span[0], 16), int(span[-1], 16), fields[1:]


def generate(source: Path) -> str:
    values = bytearray(0x110000)
    for first, last, fields in records(read(source, "SentenceBreakProperty.txt")):
        for codepoint in range(first, last + 1):
            assert values[codepoint] == 0
            values[codepoint] |= SB[fields[0]]
    ranges = []
    first = 0
    for codepoint in range(1, len(values) + 1):
        if codepoint == len(values) or values[codepoint] != values[first]:
            if values[first]:
                ranges.append((first, codepoint - 1, values[first]))
            first = codepoint
    encoded = "".join(f"{first:06X}{last:06X}{flags:02X}" for first, last, flags in ranges)
    return f'''// Generated by tools/generate_unicode_sentences.py. Do not edit.
// Unicode 17.0.0: SentenceBreakProperty. See data/unicode/17.0.0 provenance.
// Copyright (c) 1991-2025 Unicode, Inc. Distributed under Unicode License v3;
// see data/unicode/17.0.0/LICENSE.txt.
// {len(ranges)} sorted disjoint nondefault ranges; 14 ASCII bytes per record.
module ext::unicode_sentences_data;
import core::mem;

fn hex(bytes: [u8], start: i32, count: i32) -> u32 {{
    let value: u32 = 0;
    let index: i32 = 0;
    while (index < count) {{
        let digit: u32 = bytes[start + index] as u32;
        if (digit <= 57) {{ value = value * 16 + digit - 48; }}
        else {{ value = value * 16 + digit - 55; }}
        index += 1;
    }}
    return value;
}}

pub fn flags(value: u32) -> u32 {{
    let bytes: [u8] = core::mem::typed_slice_from_raw_parts<u8>(core::mem::string_data_ptr("{encoded}"), {len(encoded)});
    let low: i32 = 0;
    let high: i32 = {len(ranges)};
    while (low < high) {{
        let middle: i32 = low + (high - low) / 2;
        let at: i32 = middle * 14;
        if (value < hex(bytes, at, 6)) {{ high = middle; }}
        else {{
            if (value > hex(bytes, at + 6, 6)) {{ low = middle + 1; }}
            else {{ return hex(bytes, at + 12, 2); }}
        }}
    }}
    return 0;
}}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path, default=ROOT / "data/unicode/17.0.0")
    parser.add_argument("--output", type=Path, default=ROOT / "extended/ext/unicode_sentences_data.lani")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    read(args.data_dir, "SentenceBreakTest.txt")  # Also verify the conformance input.
    generated = generate(args.data_dir)
    if args.check:
        if args.output.read_text(encoding="utf-8") != generated:
            raise SystemExit(f"generated data differs: {args.output}")
    else:
        args.output.write_text(generated, encoding="utf-8")


if __name__ == "__main__":
    main()
