#!/usr/bin/env python3
"""Generate a source declaration inventory, without compiling or resolving code.

Declaration boundaries follow grammar/lanius.bnf. This documentation tool skips
bodies and retains source spellings; it is not a Lanius parser, package resolver,
type checker, or runtime verifier. Reviewed guides own semantic contracts.
"""
from __future__ import annotations

import argparse
from collections import Counter
from dataclasses import dataclass, field
import json
import os
from pathlib import Path, PurePosixPath
import re
import stat
import sys
import tempfile


ROOT = Path(__file__).resolve().parent.parent
BANNER = "<!-- Generated by tools/generate_library_reference.py; DO NOT EDIT. -->\n"
LAYERS = ("core", "alloc", "std", "test", "ext")
MAX_FILE_BYTES = 4 * 1024 * 1024
MAX_TOTAL_BYTES = 64 * 1024 * 1024
MAX_FILES = 4096
MAX_TOKENS_PER_FILE = 1000000
IDENTIFIER = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\Z")
PROFILES = {"Source inventory", "Unbound host declarations", "Metadata only",
            "Mixed host bindings", "Protected legacy"}


class ReferenceError(Exception):
    pass


def read_regular(path: Path, limit: int = MAX_FILE_BYTES) -> str:
    descriptor = os.open(path, os.O_RDONLY | os.O_NONBLOCK)
    try:
        if not stat.S_ISREG(os.fstat(descriptor).st_mode):
            raise ReferenceError(f"not a regular file: {path}")
        with os.fdopen(descriptor, "rb") as handle:
            descriptor = -1
            raw = handle.read(limit + 1)
        if len(raw) > limit:
            raise ReferenceError(f"file exceeds {limit} bytes: {path}")
        return raw.decode("utf-8")
    finally:
        if descriptor >= 0:
            os.close(descriptor)


@dataclass(frozen=True)
class Token:
    text: str
    start: int
    end: int
    line: int


def tokens(source: str, path: str = "<source>") -> list[Token]:
    """Keep source offsets while skipping whitespace/comments and opaque literals."""
    result = []
    index = 0
    line = 1
    while index < len(source):
        start = index
        first_line = line
        character = source[index]
        if character.isspace():
            index += 1
        elif source.startswith("//", index):
            end = source.find("\n", index + 2)
            index = len(source) if end < 0 else end
        elif source.startswith("/*", index):
            end = source.find("*/", index + 2)
            if end < 0:
                raise ReferenceError(f"{path}:{line}: unterminated block comment")
            index = end + 2
        elif character in "\"'":
            index += 1
            while index < len(source) and source[index] != character:
                index += 2 if source[index] == "\\" else 1
            if index >= len(source):
                raise ReferenceError(f"{path}:{line}: unterminated literal")
            index += 1
            result.append(Token(source[start:index], start, index, first_line))
        elif character.isascii() and (character.isalnum() or character == "_"):
            index += 1
            while (index < len(source) and source[index].isascii()
                   and (source[index].isalnum() or source[index] == "_")):
                index += 1
            result.append(Token(source[start:index], start, index, first_line))
        else:
            index += 2 if source.startswith("::", index) else 1
            result.append(Token(source[start:index], start, index, first_line))
        line += source.count("\n", start, index)
        if len(result) > MAX_TOKENS_PER_FILE:
            raise ReferenceError(f"{path}:{line}: documentation token limit exceeded")
    return result


@dataclass
class Declaration:
    kind: str
    name: str
    signature: str
    line: int
    end_line: int
    children: list[Declaration] = field(default_factory=list)


@dataclass
class Module:
    name: str
    path: str
    imports: list[tuple[str, int]]
    declarations: list[Declaration]
    public_keywords: int
    line: int = 1

    def counts(self) -> Counter:
        count = Counter()

        def visit(items):
            for item in items:
                count[item.kind] += 1
                visit(item.children)
        visit(self.declarations)
        return count


class Scanner:
    """Extract declaration spans, leaving type syntax and body semantics opaque."""

    def __init__(self, source: str, path: str):
        self.source = source
        self.path = path
        self.tokens = tokens(source, path)
        self.position = 0
        self.public_keywords = 0
        self.public_positions = set()
        self.module = ""
        self.module_line = 1
        self.imports = []
        self.private_nominals = set()
        self.public_nominals = set()

    def error(self, message, position=None):
        position = self.position if position is None else position
        line = self.tokens[position].line if position < len(self.tokens) else self.source.count("\n") + 1
        raise ReferenceError(f"{self.path}:{line}: {message}")

    def word(self, position=None):
        position = self.position if position is None else position
        return self.tokens[position].text if position < len(self.tokens) else ""

    def identifier(self, position):
        if not IDENTIFIER.fullmatch(self.word(position)):
            self.error("expected declaration identifier", position)
        return self.word(position)

    def span(self, start, stop, kind, name):
        if stop <= start:
            self.error("empty declaration span", start)
        first, last = self.tokens[start], self.tokens[stop - 1]
        return Declaration(kind, name, self.source[first.start:last.end],
                           first.line, last.line)

    def boundary(self, start, terminators):
        """Find a top-level delimiter; array counts can contain semicolons."""
        stack = []
        pairs = {")": "(", "]": "[", "}": "{"}
        for index in range(start, len(self.tokens)):
            word = self.word(index)
            if not stack and word in terminators:
                return index
            if word in "([{":
                stack.append(word)
            elif word in pairs:
                if not stack or stack.pop() != pairs[word]:
                    self.error("unmatched declaration delimiter", index)
        self.error("incomplete declaration or unclosed delimiter", start)

    def close_body(self, opening):
        if self.word(opening) != "{":
            self.error("expected opening body delimiter", opening)
        return self.boundary(opening + 1, {"}"})

    def path_declaration(self, keyword):
        start = self.position
        stop = self.boundary(start + 1, {";"})
        parts = [token.text for token in self.tokens[start + 1:stop]]
        if (not parts or len(parts) % 2 != 1
                or any(not IDENTIFIER.fullmatch(part) for part in parts[::2])
                or any(part != "::" for part in parts[1::2])):
            self.error(f"unsupported {keyword} path; expected identifiers separated by ::", start)
        name = "".join(parts)
        if keyword == "module":
            if self.module or start != 0:
                self.error("expected exactly one leading module declaration", start)
            self.module = name
            self.module_line = self.tokens[start].line
        else:
            if not self.module:
                self.error("import before module declaration", start)
            if name in {name for name, _ in self.imports}:
                self.error("duplicate declared import", start)
            self.imports.append((name, self.tokens[start].line))
        self.position = stop + 1

    def members(self, opening, closing, kind):
        """Record every field/variant of a public owner, retaining nested types."""
        result = []
        start = opening + 1
        stack = []
        pairs = {")": "(", "]": "[", ">": "<"}
        for index in range(start, closing + 1):
            word = self.word(index)
            if index == closing or (word == "," and not stack):
                if index > start:
                    name = self.identifier(start)
                    if kind == "field" and self.word(start + 1) != ":":
                        self.error("unsupported field declaration", start)
                    if kind == "variant" and index > start + 1 and self.word(start + 1) != "(":
                        self.error("unsupported enum variant declaration", start)
                    result.append(self.span(start, index, kind, name))
                elif index != closing:
                    self.error("empty field/variant declaration", start)
                start = index + 1
            elif word in ("(", "[", "<"):
                stack.append(word)
            elif word in pairs:
                if not stack or stack.pop() != pairs[word]:
                    self.error("unmatched member type delimiter", index)
            elif word in ("{", "}", ";", "pub"):
                # Semicolons inside fixed array types are expected.
                if word != ";" or not stack or stack[-1] != "[":
                    self.error("unsupported field/variant shape", index)
        if stack:
            self.error("unclosed member type delimiter", opening)
        self.unique(result)
        return result

    def unique(self, declarations):
        seen = set()
        for declaration in declarations:
            # Multiple impl blocks can extend the same type.
            if declaration.kind == "impl":
                continue
            key = (declaration.kind, declaration.name)
            if key in seen:
                raise ReferenceError(f"{self.path}:{declaration.line}: duplicate {declaration.kind} {declaration.name}")
            seen.add(key)

    def local_impl_receiver(self, declaration):
        """Recognize only a direct local nominal receiver; resolve no types."""
        header = [token.text for token in tokens(declaration.signature, self.path)]
        position = 2 if header[0] == "pub" else 1  # after impl
        parameters = set()
        if position < len(header) and header[position] == "<":
            depth, need_name = 1, True
            position += 1
            while position < len(header) and depth:
                word = header[position]
                if depth == 1 and need_name and IDENTIFIER.fullmatch(word) and word != "const":
                    parameters.add(word)
                    need_name = False
                if depth == 1 and word == ",":
                    need_name = True
                depth += (word == "<") - (word == ">")
                position += 1
            if depth:
                return None

        # Find the receiver after a top-level `for`, or directly after impl's
        # parameters for an inherent block. Bounds do not belong to the receiver.
        start, stop, depth = position, len(header), 0
        for index in range(position, len(header)):
            word = header[index]
            if depth == 0:
                if word == "for":
                    start = index + 1
                elif word == "where":
                    stop = index
                    break
            depth += (word == "<") - (word == ">")
        receiver = header[start:stop]
        if not receiver or not IDENTIFIER.fullmatch(receiver[0]):
            return None
        path, position = [receiver[0]], 1
        while position + 1 < len(receiver) and receiver[position] == "::":
            if not IDENTIFIER.fullmatch(receiver[position + 1]):
                return None
            path.append(receiver[position + 1])
            position += 2
        if position < len(receiver):
            if receiver[position] != "<":
                return None
            depth = 0
            for index in range(position, len(receiver)):
                depth += (receiver[index] == "<") - (receiver[index] == ">")
                if depth == 0 and index != len(receiver) - 1:
                    return None
            if depth:
                return None
        if len(path) == 1:
            return None if path[0] in parameters else path[0]
        return path[-1] if path[:-1] == self.module.split("::") else None

    def items(self, context="module", visible=True):
        result = []
        while self.position < len(self.tokens) and self.word() != "}":
            start = self.position
            public = self.word() == "pub"
            if public:
                self.public_keywords += 1
                self.public_positions.add(start)
                self.position += 1
            keyword = self.word()
            if keyword in ("module", "import") and context == "module" and not public:
                self.path_declaration(keyword)
                continue
            if not self.module:
                self.error("missing leading module declaration", start)
            if keyword in ("fn", "extern"):
                function = self.position
                external = keyword == "extern"
                if external:
                    function += 1
                    if self.word(function).startswith('"'):
                        function += 1
                    if self.word(function) != "fn":
                        self.error("unsupported extern declaration", start)
                name = self.identifier(function + 1)
                stop = self.boundary(function + 2, {"{", ";"})
                if not any(token.text == "(" for token in self.tokens[function + 2:stop]):
                    self.error("function has no parameter list", start)
                semicolon = self.word(stop) == ";"
                if semicolon != (external or context == "trait"):
                    self.error("unsupported function declaration terminator", stop)
                if external and context != "module":
                    self.error("unsupported extern member", start)
                kind = ("extern function" if external else "trait member" if context == "trait"
                        else "method" if context == "impl" else "function")
                if visible and (public or context == "trait"):
                    result.append(self.span(start, stop + (1 if semicolon else 0), kind, name))
                self.position = stop + 1 if semicolon else self.close_body(stop) + 1
            elif keyword in ("const", "type") and context == "module":
                name = self.identifier(self.position + 1)
                stop = self.boundary(self.position + 2, {";"})
                if not any(token.text == "=" for token in self.tokens[self.position + 2:stop]):
                    self.error("unsupported constant/type alias declaration", start)
                if public:
                    result.append(self.span(start, stop + 1, "constant" if keyword == "const" else "type alias", name))
                self.position = stop + 1
            elif keyword in ("struct", "enum", "trait", "impl") and context == "module":
                name = "" if keyword == "impl" else self.identifier(self.position + 1)
                opening = self.boundary(self.position + 1, {"{"})
                closing = self.close_body(opening)
                declaration = self.span(start, opening, keyword, name)
                if keyword in ("struct", "enum"):
                    (self.public_nominals if public else self.private_nominals).add(name)
                    if public:
                        declaration.children = self.members(opening, closing, "field" if keyword == "struct" else "variant")
                else:
                    self.position = opening + 1
                    declaration.children = self.items(keyword, visible=public if keyword == "trait" else True)
                    if self.position != closing:
                        self.error("incorrect declaration owner boundary", start)
                if public or (keyword == "impl" and declaration.children):
                    result.append(declaration)
                self.position = closing + 1
            elif keyword == "machine" and context == "module":
                # A machine (docs/state-machines-design.md) declares the
                # struct `Name` and the enum `NameState`; its header is its
                # declaration.
                name = self.identifier(self.position + 1)
                opening = self.boundary(self.position + 1, {"{"})
                closing = self.close_body(opening)
                (self.public_nominals if public else self.private_nominals).update({name, name + "State"})
                if public:
                    result.append(self.span(start, opening, "machine", name))
                self.position = closing + 1
            else:
                label = "public declaration" if public else f"{context} item"
                self.error(f"unsupported {label} shape {keyword!r}", start)
        self.unique(result)
        return result

    def scan(self):
        declarations = self.items()
        if self.position != len(self.tokens):
            self.error("unexpected closing delimiter")
        if not self.module:
            self.error("missing leading module declaration")
        for position, token in enumerate(self.tokens):
            if token.text == "pub" and position not in self.public_positions:
                self.error("unsupported public declaration marker outside inventoried item boundary", position)
        # A public trait implementation does not make its private local owner
        # public. Filter only after the complete scan, including later owners
        # and unsupported-public-syntax checks. Lexical pub counts stay intact.
        private = self.private_nominals - self.public_nominals
        declarations = [item for item in declarations
                        if item.kind != "impl" or self.local_impl_receiver(item) not in private]
        return Module(self.module, self.path, self.imports, declarations, self.public_keywords, self.module_line)


def import_targets(importer: Module, name: str, line: int,
                   known: dict[str, Module]) -> tuple[Module, tuple[Declaration, ...]]:
    """Link source declarations, retaining distinct type/value namespaces.

    Imported visibility is built/resolved separately per namespace in the
    compiler's 09e_build_import_visible_key_tables / 10b_resolve_imported_paths;
    02c2_scatter_variant_decl_records assigns enum variants to the value table.
    These links do not infer which declaration an importing use site selects.
    """
    if name in known:
        return known[name], ()
    prefix, separator, item_name = name.rpartition("::")
    if separator and prefix in known:
        owner = known[prefix]
        items = [item for item in owner.declarations if item.kind != "impl"]
        # Public enum variants also have module-level import names.
        items.extend(variant for item in owner.declarations if item.kind == "enum"
                     for variant in item.children)
        matches = [item for item in items if item.name == item_name]
        if matches:
            namespaces = ["type" if item.kind in {"type alias", "struct", "enum", "trait"}
                          else "value" for item in matches]
            if len(namespaces) != len(set(namespaces)):
                raise ReferenceError(f"{importer.path}:{line}: ambiguous public item import: {name}")
            return owner, tuple(sorted(matches, key=lambda item: item.line))
        raise ReferenceError(f"{importer.path}:{line}: public item absent from inventory: {name}")
    raise ReferenceError(f"{importer.path}:{line}: declared import absent from inventory: {name}")


def discover(root: Path) -> list[Module]:
    modules = []
    total = 0
    for directory in ("stdlib", "extended"):
        base = root / directory
        if base.is_symlink() or not base.is_dir():
            raise ReferenceError(f"expected regular source directory: {base}")
        paths = []
        for parent, directories, files in os.walk(base, followlinks=False):
            for name in directories + files:
                path = Path(parent) / name
                if path.is_symlink():
                    raise ReferenceError(f"symlink in source tree: {path}")
            paths.extend(Path(parent) / name for name in files if name.endswith(".lani"))
        for path in sorted(paths, key=lambda value: value.relative_to(root).as_posix()):
            if len(modules) >= MAX_FILES:
                raise ReferenceError("source module count limit exceeded")
            source = read_regular(path)
            total += len(source.encode("utf-8"))
            if total > MAX_TOTAL_BYTES:
                raise ReferenceError("source byte limit exceeded")
            module = Scanner(source, path.relative_to(root).as_posix()).scan()
            expected = "::".join(path.relative_to(base).with_suffix("").parts)
            if module.name != expected or module.name.split("::")[0] not in LAYERS:
                raise ReferenceError(f"{module.path}: module/path mismatch: {module.name!r} != {expected!r}")
            modules.append(module)
    names = [module.name for module in modules]
    if len(names) != len(set(names)):
        raise ReferenceError("duplicate module identity")
    known = {module.name: module for module in modules}
    for module in modules:
        for name, line in module.imports:
            import_targets(module, name, line, known)
    return sorted(modules, key=lambda module: (LAYERS.index(module.name.split("::")[0]), module.name))


def safe_relative(value: str) -> PurePosixPath:
    if not isinstance(value, str):
        raise ReferenceError("relative path must be text")
    path = PurePosixPath(value)
    if (not value or not path.parts or path.is_absolute() or path.as_posix() != value or ".." in path.parts
            or "\\" in value or any(ord(char) < 32 or ord(char) == 127 for char in value)):
        raise ReferenceError(f"unsafe relative path: {value!r}")
    return path


def load_metadata(root: Path, modules: list[Module]) -> dict:
    def unique_keys(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ReferenceError(f"duplicate metadata key: {key}")
            result[key] = value
        return result

    metadata = json.loads(read_regular(root / "tools/library_reference_metadata.json"), object_pairs_hook=unique_keys)
    if not isinstance(metadata, dict) or set(metadata) != {"modules"} or not isinstance(metadata["modules"], dict):
        raise ReferenceError("metadata requires a modules mapping")
    known = {module.name: module for module in modules}
    for name, entry in metadata["modules"].items():
        if name not in known or not isinstance(entry, dict):
            raise ReferenceError(f"metadata references unknown module: {name}")
        if set(entry) - {"guides", "role", "profile", "note", "declarations"}:
            raise ReferenceError(f"unknown metadata field: {name}")
        if entry.get("role", "module") not in ("module", "support") or entry.get("profile", "Source inventory") not in PROFILES:
            raise ReferenceError(f"invalid role/profile: {name}")
        guides = entry.get("guides", [])
        if (not isinstance(guides, list) or any(not isinstance(guide, str) for guide in guides)
                or len(guides) != len(set(guides))):
            raise ReferenceError(f"invalid/duplicate guide list: {name}")
        for guide in guides:
            path = safe_relative(guide)
            if path.parts[0] != "docs" or path.suffix != ".md":
                raise ReferenceError(f"invalid guide path: {guide}")
            current = root
            for part in path.parts:
                current /= part
                if current.is_symlink():
                    raise ReferenceError(f"symlinked guide: {guide}")
            read_regular(current)
        if not isinstance(entry.get("note", ""), str):
            raise ReferenceError(f"invalid note: {name}")
        notes = entry.get("declarations", {})
        free_names = {item.name for item in known[name].declarations if item.kind in ("function", "extern function")}
        if (not isinstance(notes, dict) or any(key not in free_names or not isinstance(value, str)
                                             for key, value in notes.items())):
            raise ReferenceError(f"declaration notes require existing free function names: {name}")
    return metadata["modules"]


def markdown_text(value):
    return value.replace("\\", "\\\\").replace("|", "\\|").replace("[", "\\[").replace("]", "\\]").replace("<", "&lt;").replace(">", "&gt;")


def link(from_path: str, to_path: str, label: str, line: int | None = None):
    relative = os.path.relpath(to_path, Path(from_path).parent).replace(os.sep, "/")
    return f"[{markdown_text(label)}]({relative}" + (f"#L{line}" if line else "") + ")"


def page_path(module: Module):
    return "docs/api/" + module.name.replace("::", "/") + ".md"


def code(signature):
    longest = max((len(match[0]) for match in re.finditer(r"`+", signature)), default=0)
    fence = "`" * max(3, longest + 1)
    return f"{fence}lanius\n{signature}\n{fence}\n"


def render_module(module: Module, metadata: dict, known: dict) -> str:
    path = page_path(module)
    result = [BANNER, f"# `{module.name}` — declaration reference\n",
              "Generated source inventory. Linked guides own runtime and semantic contracts; "
              "a listed declaration does not establish executable behavior.\n",
              link(path, "docs/api/README.md", "All modules") + " · " + link(path, module.path, "Source", module.line) + "\n",
              f"Layer: `{module.name.split('::')[0]}`. "
              f"Role: {'support/implementation data' if metadata.get('role') == 'support' else 'module'}. "
              f"Profile: **{metadata.get('profile', 'Source inventory')}**.\n"]
    if metadata.get("note"):
        result.append(metadata["note"] + "\n")
    if metadata.get("guides"):
        result.append("## Contract and evidence guides\n")
        result.extend("- " + link(path, guide, PurePosixPath(guide).stem) for guide in metadata["guides"])
        result.append("")
    else:
        result.append("**No contract guide registered.** This page makes no runtime support claim.\n")
    counts = module.counts()
    result.append("Declaration counts: " + ("; ".join(f"{name}: {count}" for name, count in sorted(counts.items())) or "none") + ".\n")
    result.append("## Declared imports\n")
    if not module.imports:
        result.append("None.\n")
    else:
        result.append("Direct source imports; this is not a package-resolution or transitive dependency result.\n")
        for name, line in module.imports:
            target, items = import_targets(module, name, line, known)
            imported = "- " + link(path, page_path(target), name)
            if len(items) == 1:
                item = items[0]
                imported += f" (item: {item.kind}) · " + link(path, target.path, "declaration", item.line)
            elif items:
                imported += " (items in separate namespaces: " + ", ".join(item.kind for item in items) + "; no use-site resolution)"
                for item in items:
                    imported += " · " + link(path, target.path, f"{item.kind} declaration", item.line)
            result.append(imported + " · " + link(path, module.path, "source", line))
        result.append("")
    groups = [("Types, fields and variants", {"type alias", "struct", "enum", "machine"}),
              ("Constants", {"constant"}), ("Free functions and extern declarations", {"function", "extern function"}),
              ("Traits and members", {"trait"}), ("Implementation blocks and public methods", {"impl"})]
    for title, kinds in groups:
        items = [item for item in module.declarations if item.kind in kinds]
        if not items:
            continue
        result.extend([f"## {title}\n"])
        if any(item.kind in ("struct", "enum") for item in items):
            result.append("Fields and variants are retained under their declared public owner. "
                          "Their representation does not establish safe construction or mutation; consult the guides.\n")
        for item in items:
            label = f"{item.kind}: {item.name}" if item.name else f"impl at line {item.line}"
            result.extend([f"### {markdown_text(label)}\n", link(path, module.path, f"Source line {item.line}", item.line) + "\n",
                           code(item.signature)])
            if item.kind == "extern function":
                result.append("Extern declaration; binding availability is not inferred.\n")
            if item.name in metadata.get("declarations", {}):
                result.append(metadata["declarations"][item.name] + "\n")
            for child in item.children:
                result.extend([f"#### {markdown_text(child.kind + ': ' + child.name)}\n",
                               link(path, module.path, f"Source line {child.line}", child.line) + "\n", code(child.signature)])
    return "\n".join(result).rstrip() + "\n"


def render_index(modules: list[Module], metadata: dict) -> str:
    path = "docs/api/README.md"
    result = [BANNER, "# Generated library declaration reference\n",
              "This source inventory lists declarations from `stdlib/` and `extended/`. "
              "It improves discovery; it does not complete the semantic API reference. "
              "Linked guides own runtime behavior, ownership, errors, numerical limits and target evidence. "
              "A declaration, method body or source import is not execution evidence.\n",
              "The documentation scanner preserves declaration spellings and bounds, skips function bodies, "
              "and records enclosing impl/trait headers. It is not a compiler, type checker or package resolver. "
              "Support modules remain visible separately from ordinary modules. New modules default to source "
              "inventory with an explicitly unregistered guide.\n",
              link(path, "docs/library-api-reference.md", "Generation and verification") + " · "
              + link(path, "docs/library-api-conventions.md", "API conventions") + " · "
              + link(path, "docs/library-roadmap.md", "Remaining library work") + "\n",
              f"Inventory: **{len(modules)} modules**, "
              f"**{sum(sum(module.counts().values()) for module in modules)} declaration/member entries**. "
              "Counts include fields, variants, trait members and separate impl blocks; they are not a count of verified operations.\n"]
    for role, heading in (("module", "Modules"), ("support", "Support and implementation data")):
        result.append(f"## {heading}\n")
        for layer in LAYERS:
            selected = [module for module in modules if module.name.split("::")[0] == layer
                        and metadata.get(module.name, {}).get("role", "module") == role]
            if not selected:
                continue
            result.extend([f"### `{layer}`\n", "| Module | Source | Entries | Profile | Contract guides |",
                           "| --- | --- | ---: | --- | --- |"])
            for module in selected:
                entry = metadata.get(module.name, {})
                guides = ", ".join(link(path, guide, PurePosixPath(guide).stem) for guide in entry.get("guides", [])) or "**Unregistered**"
                result.append("| " + " | ".join([link(path, page_path(module), module.name), link(path, module.path, "source", module.line),
                              str(sum(module.counts().values())), entry.get("profile", "Source inventory"), guides]) + " |")
            result.append("")
    unlinked = [module for module in modules if not metadata.get(module.name, {}).get("guides")]
    result.append("## Modules without a registered contract guide\n")
    result.append("These are discovery/contract-link gaps, not claims that their code is missing or executable.\n")
    result.extend("- " + link(path, page_path(module), module.name) for module in unlinked)
    if not unlinked:
        result.append("None in this source snapshot.")
    return "\n".join(result).rstrip() + "\n"


def generate(root: Path) -> tuple[dict[str, str], list[Module]]:
    modules = discover(root)
    metadata = load_metadata(root, modules)
    known = {module.name: module for module in modules}
    output = {"docs/api/README.md": render_index(modules, metadata)}
    output.update({page_path(module): render_module(module, metadata.get(module.name, {}), known) for module in modules})
    return output, modules


def publish(root: Path, output: dict[str, str], check: bool) -> list[str]:
    """Preflight all destinations; replace/delete only files with our exact banner."""
    base = root / "docs/api"
    if (root / "docs").is_symlink() or base.is_symlink():
        raise ReferenceError("symlinked output directory")
    existing = {}
    if base.exists():
        if not base.is_dir():
            raise ReferenceError("output path is not a directory")
        for parent, directories, files in os.walk(base, followlinks=False):
            for name in directories + files:
                if (Path(parent) / name).is_symlink():
                    raise ReferenceError("symlink in generated output tree")
            for name in files:
                target = Path(parent) / name
                existing[target.relative_to(root).as_posix()] = read_regular(target)
    for name in output:
        relative = safe_relative(name)
        if relative.parts[:2] != ("docs", "api") or relative.suffix != ".md":
            raise ReferenceError(f"output outside generated tree: {name}")
        if name in existing and not existing[name].startswith(BANNER):
            raise ReferenceError(f"refusing to replace non-generated file: {name}")
        for parent in (root / name).parents:
            if parent == root:
                break
            if parent.exists() and not parent.is_dir():
                raise ReferenceError(f"non-directory output ancestor: {parent}")
    stale = sorted(name for name, text in existing.items() if text.startswith(BANNER) and name not in output)
    changed = sorted(name for name, text in output.items() if existing.get(name) != text)
    if not check:
        for name in changed:
            target = root / name
            target.parent.mkdir(parents=True, exist_ok=True)
            temporary = None
            try:
                with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n",
                                                 dir=target.parent, prefix=".reference-", delete=False) as handle:
                    temporary = Path(handle.name)
                    handle.write(output[name])
                temporary.chmod(0o644)
                temporary.replace(target)
            finally:
                if temporary is not None:
                    temporary.unlink(missing_ok=True)
        for name in stale:
            (root / name).unlink()
    return changed + stale


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare generated output without modifying files")
    options = parser.parse_args(argv)
    try:
        output, modules = generate(ROOT)
        changed = publish(ROOT, output, options.check)
        if options.check and changed:
            print("declaration reference is stale:\n" + "\n".join(changed), file=sys.stderr)
            return 1
        print(f"{'Checked' if options.check else 'Generated'} {len(output)} pages from {len(modules)} source modules; "
              f"{sum(module.public_keywords for module in modules)} public declaration markers inventoried. "
              "No execution verification performed.")
        return 0
    except (ReferenceError, OSError, UnicodeError, ValueError, TypeError) as error:
        print(f"declaration reference: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
