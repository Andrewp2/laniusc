#!/usr/bin/env python3
"""Compile the sample's GLSL with glslang, validate SPIR-V, embed native words.
This is sample data generation, not a Lanius shader compiler or GPU runtime.
"""
import pathlib,struct,subprocess,tempfile,argparse
ROOT=pathlib.Path(__file__).resolve().parents[1]
def generate():
    parts=['// Generated by tools/generate_gpu_life.py; sample data only.','module shaders::life_shaders;']
    with tempfile.TemporaryDirectory() as tmp:
        for stage in ['vert','frag','comp']:
            output=pathlib.Path(tmp)/(stage+'.spv')
            subprocess.run(['glslangValidator','-V','--target-env','vulkan1.1',str(ROOT/'sample_programs/library/shaders'/('life.'+stage)),'-o',str(output)],check=True,capture_output=True,timeout=30)
            subprocess.run(['spirv-val','--target-env','vulkan1.1',str(output)],check=True,timeout=30)
            data=output.read_bytes(); words=struct.unpack('<'+'i'*(len(data)//4),data)
            parts.append(f'pub fn {stage}() -> [i32;{len(words)}] {{ return [')
            parts.extend('    '+','.join(str(n) for n in words[i:i+12])+(',' if i+12<len(words) else '') for i in range(0,len(words),12))
            parts.append(']; }')
    return '\n'.join(parts)+'\n'
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args();result=generate();path=ROOT/'sample_programs/library/shaders/life_shaders.lani'
if args.check:
    if path.read_text()!=result: raise SystemExit('Life shader data differs; regenerate with the recorded toolchain')
else: path.write_text(result)
