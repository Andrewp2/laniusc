#!/usr/bin/env python3
"""Generate stdlib/core/float_tables.lani: Eisel-Lemire and Schubfach power tables,
and shaders/float_decimal_pow5.slang: the same powers of five for the GPU
literal parser (shaders/float_decimal.slang).

pow5: for q in [-342, 308], the 128-bit truncated/normalized 5^q used by the
Eisel-Lemire parser (same construction as fast_float and Rust's dec2flt).
g: for k in [-324, 292], Schubfach's 126-bit g(k) = floor(10^-k / 2^r) + 1.
"""
from fractions import Fraction
from pathlib import Path

def pow5():
    out = []
    for q in range(-342, 0):
        p = 5 ** -q
        z = p.bit_length()
        if q >= -27:
            c = 2 ** (z + 127) // p + 1
        else:
            c = 2 ** (2 * z + 128) // p + 1
            while c >= 1 << 128:
                c //= 2
        out.append(c)
    for q in range(0, 309):
        p = 5 ** q
        while p < 1 << 127:
            p *= 2
        while p >= 1 << 128:
            p //= 2
        out.append(p)
    assert out[0] == (0xeef453d6923bd65a << 64) | 0x113faa2906a13b3f
    return out


def schubfach():
    """g(k) = floor(10^-k * 2^-r) + 1 with r = floor(-k log2 10) - 125, so
    2^125 < g <= 2^126, for k in [-324, 292] (Giulietti's Schubfach)."""
    out = []
    for k in range(-324, 293):
        e = -k
        r = ((e * 913124641741) >> 38) - 125
        v = Fraction(10) ** e / Fraction(2) ** r
        assert 2 ** 125 <= v < 2 ** 126
        out.append(int(v) + 1)
    return out


def tree(values, lo, hi, indent):
    # Binary search over literal returns: about log2(n) comparisons per
    # lookup and no table decoding.
    pad = '    ' * indent
    if hi - lo == 1:
        v = values[lo]
        return [pad + 'return Power { high: %d, low: %d };' % (v >> 64, v & ((1 << 64) - 1))]
    mid = (lo + hi) // 2
    return ([pad + 'if (i < %d) {' % mid] + tree(values, lo, mid, indent + 1) + [pad + '}']
            + tree(values, mid, hi, indent))


def main():
    p5 = pow5()
    g = schubfach()
    lines = [
        '// Generated by tools/generate_float_tables.py; do not edit.',
        '// Eisel-Lemire 128-bit powers of five for q in [-342, 308] and',
        '// Schubfach 126-bit powers of ten for k in [-324, 292].',
        'module core::float_tables;',
        '',
        '// A 128-bit table value high * 2^64 + low.',
        'pub struct Power { high: u64, low: u64 }',
        'pub const POW5_MIN: i32 = -342;',
        'pub const POW5_MAX: i32 = 308;',
        'pub const G_MIN: i32 = -324;',
        'pub const G_MAX: i32 = 292;',
        '// The 128-bit normalized power of five 5^q for q in [POW5_MIN, POW5_MAX]',
        '// (as fast_float and Rust dec2flt build it); zero outside.',
        'pub fn pow5(q: i32) -> Power {',
        '    let i: i32 = q + 342;',
        '    if (i < 0 || i >= %d) { return Power { high: 0, low: 0 }; }' % len(p5),
    ]
    lines += tree(p5, 0, len(p5), 1)
    lines += [
        '}',
        '// High and low 64 bits of pow5(q).',
        'pub fn pow5_high(q: i32) -> u64 { return pow5(q).high; }',
        'pub fn pow5_low(q: i32) -> u64 { return pow5(q).low; }',
        '// Schubfach g(k) for k in [G_MIN, G_MAX]: floor(10^-k / 2^r) + 1 with',
        '// r = floor(-k log2 10) - 125, so 2^125 < g <= 2^126; zero outside.',
        'pub fn schubfach_g(k: i32) -> Power {',
        '    let i: i32 = k + 324;',
        '    if (i < 0 || i >= %d) { return Power { high: 0, low: 0 }; }' % len(g),
    ]
    lines += tree(g, 0, len(g), 1)
    lines += ['}', '']
    root = Path(__file__).resolve().parent.parent
    root.joinpath('stdlib/core/float_tables.lani').write_text('\n'.join(lines))
    root.joinpath('shaders/float_decimal_pow5.slang').write_text(slang_pow5(p5))


def slang_pow5(values):
    words = []
    for v in values:
        high, low = v >> 64, v & ((1 << 64) - 1)
        words += [high & 0xffffffff, high >> 32, low & 0xffffffff, low >> 32]
    lines = [
        '// Generated by tools/generate_float_tables.py; do not edit.',
        '// Eisel-Lemire 128-bit powers of five 5^q for q in [-342, 308], built as',
        '// fast_float and Rust dec2flt build them. Entry q + 342 is four words:',
        '// the high 64 bits (low word first), then the low 64 bits.',
        'static const uint FLOAT_DECIMAL_POW5_MIN = 342u;',
        'static const uint FLOAT_DECIMAL_POW5[%d] = {' % len(words),
    ]
    for at in range(0, len(words), 4):
        lines.append('    ' + ', '.join('0x%08xu' % w for w in words[at:at + 4]) + ',')
    lines += ['};', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    main()
