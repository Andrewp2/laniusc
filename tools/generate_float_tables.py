#!/usr/bin/env python3
"""Generate stdlib/core/float_tables.lani: Eisel-Lemire and Grisu power tables.

pow5: for q in [-342, 308], the 128-bit truncated/normalized 5^q used by the
Eisel-Lemire parser (same construction as fast_float and Rust's dec2flt).
cached: for k in -348, -340, ..., 340, the nearest 64-bit normalized
significand f and binary exponent e with 10^k ~= f * 2^e (Grisu cached powers).
"""
from fractions import Fraction
from pathlib import Path

CHUNK = 124


def pow5():
    out = []
    for q in range(-342, 0):
        p = 5 ** -q
        z = p.bit_length()
        if q >= -27:
            c = 2 ** (z + 127) // p + 1
        else:
            c = 2 ** (2 * z + 128) // p + 1
            while c >= 1 << 128:
                c //= 2
        out.append(c)
    for q in range(0, 309):
        p = 5 ** q
        while p < 1 << 127:
            p *= 2
        while p >= 1 << 128:
            p //= 2
        out.append(p)
    assert out[0] == (0xeef453d6923bd65a << 64) | 0x113faa2906a13b3f
    return out


def cached():
    out = []
    for k in range(-348, 341, 8):
        v = Fraction(10) ** k
        e = v.numerator.bit_length() - v.denominator.bit_length() - 64
        while v / Fraction(2) ** e >= 2 ** 64:
            e += 1
        while v / Fraction(2) ** e < 2 ** 63:
            e -= 1
        f = v / Fraction(2) ** e
        whole = int(f)
        rest = f - whole
        if rest > Fraction(1, 2) or (rest == Fraction(1, 2) and whole & 1):
            whole += 1
        if whole == 2 ** 64:
            whole //= 2
            e += 1
        out.append((whole, e))
    assert out[0] == (0xfa8fd5a0081c0288, -1220)
    return out


def chunks(name, entries, width):
    lines = ['fn %s_chunk(index: i32) -> [u8] {' % name]
    count = (len(entries) + CHUNK - 1) // CHUNK
    for c in range(count):
        text = ''.join(entries[c * CHUNK:(c + 1) * CHUNK])
        lines.append('    if (index == %d) { let text: str = "%s"; return core::mem::typed_slice_from_raw_parts(core::mem::string_data_ptr(text), %d); }'
                     % (c, text, len(text)))
    lines.append('    let none: str = ""; return core::mem::typed_slice_from_raw_parts(core::mem::string_data_ptr(none), 0);')
    lines.append('}')
    return lines


def main():
    p5 = ['%032x' % v for v in pow5()]
    cp = ['%016x%04x' % (f, e + 32768) for f, e in cached()]
    lines = [
        '// Generated by tools/generate_float_tables.py; do not edit.',
        '// Eisel-Lemire 128-bit powers of five for q in [-342, 308] and Grisu',
        '// 64-bit cached powers of ten 10^(-348 + 8i), i in [0, 86].',
        'module core::float_tables;',
        'import core::mem;',
        '',
        'fn hex(bytes: [u8], offset: i32, width: i32) -> u64 {',
        '    let value: u64 = 0; let i: i32 = 0;',
        '    while (i < width) { let b: u8 = bytes[offset + i]; let d: u64 = (b as u64) - 48; if (b >= 97) { d = (b as u64) - 87; } value = (value << 4) | d; i += 1; }',
        '    return value;',
        '}',
    ]
    lines += chunks('pow5', p5, 32)
    lines += chunks('cached', cp, 20)
    lines += [
        'pub const POW5_MIN: i32 = -342;',
        'pub const POW5_MAX: i32 = 308;',
        'pub const CACHED_COUNT: i32 = %d;' % len(cp),
        '// High and low 64 bits of the 128-bit power of five 5^q.',
        'pub fn pow5_high(q: i32) -> u64 { let i: i32 = q + 342; return hex(pow5_chunk(i / %d), (i %% %d) * 32, 16); }' % (CHUNK, CHUNK),
        'pub fn pow5_low(q: i32) -> u64 { let i: i32 = q + 342; return hex(pow5_chunk(i / %d), (i %% %d) * 32 + 16, 16); }' % (CHUNK, CHUNK),
        '// Cached power i approximates 10^(-348 + 8i) as significand * 2^exponent.',
        'pub fn cached_significand(i: i32) -> u64 { return hex(cached_chunk(i / %d), (i %% %d) * 20, 16); }' % (CHUNK, CHUNK),
        'pub fn cached_exponent(i: i32) -> i32 { return (hex(cached_chunk(i / %d), (i %% %d) * 20 + 16, 4) as i32) - 32768; }' % (CHUNK, CHUNK),
        'pub fn cached_decimal(i: i32) -> i32 { return -348 + 8 * i; }',
        '',
    ]
    Path(__file__).resolve().parent.parent.joinpath('stdlib/core/float_tables.lani').write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
