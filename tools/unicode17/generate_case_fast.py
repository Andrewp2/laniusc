#!/usr/bin/env python3
"""Translate vendored Unicode 17.0.0 data into a two-level casing table.

stage1[cp >> 7] -> block, stage2[block * 128 + (cp & 127)] -> slot,
stage3[slot] -> 2 hex flag digits + four 6-digit deltas (mod 2^24):
simple lowercase, simple uppercase, simple titlecase and C+S case fold.
Flag bits: 0 Cased, 1 Case_Ignorable, 2 ccc == 0, 3 ccc == 230,
4 SpecialCasing row (any locale or context), 5 full folding differs from the
simple fold (an F or T record), 6 Soft_Dotted.
ext::unicode_case uses the deltas only when bit 4 (lower/upper/title) or bit 5
(fold) is clear; otherwise it keeps the SpecialCasing/full-folding search.
Inputs are hash-checked files under data/unicode/17.0.0. No host Unicode
database is read.
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_normalization import read, ranges  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "extended/ext/unicode_case_fast_data.lani"
BLOCK = 128
MASK = (1 << 24) - 1


def generate():
    lower, upper, title, ccc = {}, {}, {}, {}
    first = None
    for line in read("UnicodeData.txt").splitlines():
        f = line.split(";")
        cp = int(f[0], 16)
        if f[1].endswith(", First>"):
            first = cp
            continue
        if f[1].endswith(", Last>"):
            for c in range(first, cp + 1):
                if f[3] != "0":
                    ccc[c] = int(f[3])
            continue
        if f[3] != "0":
            ccc[cp] = int(f[3])
        if f[12]:
            upper[cp] = int(f[12], 16)
        if f[13]:
            lower[cp] = int(f[13], 16)
        if f[14]:
            title[cp] = int(f[14], 16)
    core = read("DerivedCoreProperties.txt")
    cased, ignorable = ranges(core, "Cased"), ranges(core, "Case_Ignorable")
    soft = ranges(read("PropList.txt"), "Soft_Dotted")
    simple_fold, slow_fold = {}, set()
    for raw in read("CaseFolding.txt").splitlines():
        body = raw.split("#", 1)[0].strip()
        if not body:
            continue
        cols = [x.strip() for x in body.split(";")]
        cp = int(cols[0], 16)
        if cols[1] in ("C", "S"):
            simple_fold[cp] = int(cols[2], 16)
        if cols[1] in ("F", "T"):
            slow_fold.add(cp)
    special = set()
    for raw in read("SpecialCasing.txt").splitlines():
        body = raw.split("#", 1)[0].strip()
        if body:
            special.add(int(body.split(";")[0], 16))

    # ext::unicode_case hard-codes Root-locale ASCII; prove its assumptions.
    assert sorted(c for c in ignorable if c < 128) == [39, 46, 58, 94, 96]
    assert sorted(c for c in cased if c < 128) == list(range(65, 91)) + list(range(97, 123))
    assert all(ccc.get(c, 0) == 0 and c not in slow_fold - {0x49} for c in range(128))
    assert all(lower.get(c, c) == (c + 32 if 65 <= c <= 90 else c) for c in range(128))
    assert all(upper.get(c, c) == (c - 32 if 97 <= c <= 122 else c) == title.get(c, upper.get(c, c)) for c in range(128))
    assert all(simple_fold.get(c, c) == lower.get(c, c) for c in range(128))

    def record(cp):
        u = upper.get(cp, cp)
        maps = (lower.get(cp, cp), u, title.get(cp, u), simple_fold.get(cp, cp))
        c = ccc.get(cp, 0)
        flags = ((cp in cased) | (cp in ignorable) << 1 | (c == 0) << 2 | (c == 230) << 3
                 | (cp in special) << 4 | (cp in slow_fold) << 5 | (cp in soft) << 6)
        return (flags,) + tuple((m - cp) & MASK for m in maps)

    records = [record(cp) for cp in range(0x110000)]
    distinct = sorted(set(records))
    slot = {r: i for i, r in enumerate(distinct)}
    blocks, stage1 = {}, []
    for b in range(0x110000 // BLOCK):
        key = tuple(slot[r] for r in records[b * BLOCK:(b + 1) * BLOCK])
        stage1.append(blocks.setdefault(key, len(blocks)))
    stage2 = [s for key, _ in sorted(blocks.items(), key=lambda kv: kv[1]) for s in key]
    w1, w2 = len(f"{len(blocks) - 1:X}"), len(f"{len(distinct) - 1:X}")
    s1 = "".join(f"{x:0{w1}X}" for x in stage1)
    s2 = "".join(f"{x:0{w2}X}" for x in stage2)
    s3 = "".join(f"{r[0]:02X}" + "".join(f"{d:06X}" for d in r[1:]) for r in distinct)
    out = [
        "// Generated by tools/unicode17/generate_case_fast.py; do not edit.",
        "// Unicode 17.0.0 UnicodeData, DerivedCoreProperties, PropList, CaseFolding and",
        "// SpecialCasing; see data/unicode/17.0.0. Copyright (c) 1991-2025 Unicode, Inc.",
        "// Distributed under Unicode License v3; see data/unicode/17.0.0/LICENSE.txt.",
        f"// Two-level table: {len(stage1)} blocks of {BLOCK}, {len(blocks)} distinct blocks,",
        f"// {len(distinct)} distinct records (flags + lower/upper/title/fold deltas mod 2^24).",
        "module ext::unicode_case_fast_data;", "import core::mem;", "",
        "pub const CASED: u32 = 1;", "pub const CASE_IGNORABLE: u32 = 2;", "pub const CCC_ZERO: u32 = 4;",
        "pub const CCC_ABOVE: u32 = 8;", "pub const SPECIAL: u32 = 16;", "pub const FULL_FOLD: u32 = 32;",
        "pub const SOFT_DOTTED: u32 = 64;", "",
        "fn number(data: [u8], at: i32, width: i32) -> u32 {",
        "    let value: u32 = 0; let index: i32 = 0;",
        "    while (index < width) {",
        "        let byte: u8 = data[at + index]; let digit: u32 = (byte - 48) as u32;",
        "        if (byte >= 65) { digit = (byte - 55) as u32; }",
        "        value = value * 16 + digit; index += 1;",
        "    }", "    return value;", "}",
        "fn records() -> [u8] {",
        f'    let third: str = "{s3}";',
        f"    return core::mem::typed_slice_from_raw_parts(core::mem::string_data_ptr(third), {len(s3)});",
        "}", "",
        "// Precondition: value <= 0x10FFFF. Returns the record slot.",
        "pub fn slot(value: u32) -> i32 {",
        f'    let first: str = "{s1}";',
        f"    let stage1: [u8] = core::mem::typed_slice_from_raw_parts(core::mem::string_data_ptr(first), {len(s1)});",
        f'    let second: str = "{s2}";',
        f"    let stage2: [u8] = core::mem::typed_slice_from_raw_parts(core::mem::string_data_ptr(second), {len(s2)});",
        f"    let block: u32 = number(stage1, ((value >> 7) * {w1}) as i32, {w1});",
        f"    return number(stage2, (((block << 7) + (value & 127)) * {w2}) as i32, {w2}) as i32;",
        "}",
        "pub fn flags(slot: i32) -> u32 { return number(records(), slot * 26, 2); }",
        "// kind: 0 lowercase, 1 uppercase, 2 titlecase, 3 simple C+S fold.",
        "pub fn map(value: u32, slot: i32, kind: i32) -> u32 {",
        "    return (value + number(records(), slot * 26 + 2 + kind * 6, 6)) & 16777215;",
        "}", "",
    ]
    return "\n".join(out)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = generate()
    if args.check:
        assert TARGET.read_text() == source, f"stale generated table: {TARGET}"
    else:
        TARGET.write_text(source)
