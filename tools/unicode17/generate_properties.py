#!/usr/bin/env python3
"""Translate checked-in Unicode 17.0.0 UCD files into static Lanius tables.

This tool only transforms authoritative data. Runtime searches, property queries,
and scalar mappings are implemented in Lanius. No Python Unicode database is used.
"""
from __future__ import annotations
import argparse
import gzip
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VERSION = "17.0.0"
CATEGORIES = "Cn Lu Ll Lt Lm Lo Mn Mc Me Nd Nl No Pc Pd Ps Pe Pi Pf Po Sm Sc Sk So Zs Zl Zp Cc Cf Cs Co".split()
PROPERTIES = "Alphabetic Lowercase Uppercase Cased Case_Ignorable White_Space XID_Start XID_Continue Default_Ignorable_Code_Point".split()
NOTICE = """// Generated by tools/unicode17/generate_properties.py; do not edit.
// Unicode Character Database 17.0.0, https://www.unicode.org/Public/17.0.0/ucd/
// Copyright (c) 1991-2025 Unicode, Inc. Unicode and the Unicode Logo are
// registered trademarks of Unicode, Inc. in the U.S. and other countries.
// Distributed under the Unicode License v3; see data/unicode/17.0.0/LICENSE.txt.
"""


def lines(data: Path, name: str):
    with gzip.open(data / (name + ".gz"), "rt", encoding="utf-8") as stream:
        yield from stream


def unicode_rows(data: Path):
    first = None
    for line in lines(data, "UnicodeData.txt"):
        fields = line.rstrip("\n").split(";")
        cp = int(fields[0], 16)
        if fields[1].endswith(", First>"):
            assert first is None
            first = (cp, fields)
        elif fields[1].endswith(", Last>"):
            assert first is not None and fields[2:] == first[1][2:]
            yield first[0], cp, fields
            first = None
        else:
            yield cp, cp, fields
    assert first is None


def dispatch(chunks: list[str], width: int, records_per_chunk: int, lo=0, hi=None, indent="    "):
    if hi is None:
        hi = len(chunks)
    if hi - lo == 1:
        text = chunks[lo]
        return (f'{indent}let text: str = "{text}";\n'
                f'{indent}return core::mem::typed_slice_from_raw_parts(core::mem::string_data_ptr(text), {len(text)});\n')
    mid = (lo + hi) // 2
    return (f"{indent}if (index < {mid * records_per_chunk}) {{\n"
            + dispatch(chunks, width, records_per_chunk, lo, mid, indent + "    ")
            + f"{indent}}} else {{\n"
            + dispatch(chunks, width, records_per_chunk, mid, hi, indent + "    ")
            + f"{indent}}}\n")


def table(name: str, records: list[str], range_table=False):
    assert records
    width = len(records[0])
    assert all(len(row) == width for row in records)
    per = 4000 // width
    chunks = ["".join(records[at:at+per]) for at in range(0, len(records), per)]
    source = NOTICE + f"module core::{name};\nimport core::mem;\nimport core::unicode_table;\n\n"
    source += "fn chunk(index: i32) -> [u8] {\n" + dispatch(chunks, width, per) + "}\n"
    source += (f"fn field(index: i32, offset: i32, width: i32) -> u32 {{\n"
               f"    return core::unicode_table::hex(chunk(index), (index % {per}) * {width} + offset, width);\n}}\n")
    source += f"pub fn find(value: u32) -> i32 {{\n    let lo: i32 = 0; let hi: i32 = {len(records)};\n"
    source += "    while (lo < hi) {\n        let mid: i32 = lo + (hi - lo) / 2;\n        let key: u32 = field(mid, 0, 6);\n"
    if range_table:
        source += "        if (key <= value) { lo = mid + 1; } else { hi = mid; }\n    }\n    return lo - 1;\n}\n"
    else:
        source += "        if (key < value) { lo = mid + 1; } else { hi = mid; }\n    }\n"
        source += f"    if (lo < {len(records)} && field(lo, 0, 6) == value) {{ return lo; }}\n    return -1;\n}}\n"
    source += "pub fn read(index: i32, offset: i32, width: i32) -> u32 { return field(index, offset, width); }\n"
    return source


def generate(data: Path):
    size = 0x110000
    # bits: category[0:5], CCC[5:13], binary flags[13:22], decimal[22:26].
    values = [10 << 22] * size
    casing = {}
    for first, last, row in unicode_rows(data):
        cat, ccc = CATEGORIES.index(row[2]), int(row[3])
        digit = int(row[6]) if row[6] else 10
        value = cat | (ccc << 5) | (digit << 22)
        values[first:last+1] = [value] * (last-first+1)
        if first == last:
            lower = int(row[13], 16) if row[13] else first
            upper = int(row[12], 16) if row[12] else first
            # UAX44: missing Simple_Titlecase_Mapping defaults to simple uppercase.
            title = int(row[14], 16) if row[14] else upper
            if (lower, upper, title) != (first, first, first):
                casing[first] = [lower, upper, title, first]
    for name in ["DerivedCoreProperties.txt", "PropList.txt"]:
        for line in lines(data, name):
            body = line.split("#", 1)[0].strip()
            if not body:
                continue
            columns = [x.strip() for x in body.split(";")]
            if columns[1] not in PROPERTIES:
                continue
            flag = 1 << (13 + PROPERTIES.index(columns[1]))
            ends = columns[0].split("..")
            first, last = int(ends[0], 16), int(ends[-1], 16)
            for cp in range(first, last+1):
                values[cp] |= flag
    folds, turkic = {}, {}
    for line in lines(data, "CaseFolding.txt"):
        body = line.split("#", 1)[0].strip()
        if not body:
            continue
        columns = [x.strip() for x in body.split(";")]
        cp = int(columns[0], 16)
        mapped = [int(x, 16) for x in columns[2].split()]
        assert 1 <= len(mapped) <= 3
        status = columns[1]
        if status in ["C", "S"]:
            assert len(mapped) == 1
            casing.setdefault(cp, [cp]*4)[3] = mapped[0]
        if status in ["C", "F"]:
            folds[cp] = mapped
        if status == "T":
            turkic[cp] = mapped
    properties = [f"{cp:06X}{value:07X}" for cp, value in enumerate(values) if cp == 0 or value != values[cp-1]]
    scalar = [f"{cp:06X}" + "".join(f"{v:06X}" for v in mapped) for cp, mapped in sorted(casing.items())]
    def fold_records(mapping):
        return [f"{cp:06X}{len(mapped):X}" + "".join(f"{v:06X}" for v in mapped + [0]*(3-len(mapped))) for cp, mapped in sorted(mapping.items())]
    return {
        "unicode_properties_data.lani": table("unicode_properties_data", properties, True),
        "unicode_case_data.lani": table("unicode_case_data", scalar),
        "unicode_fold_data.lani": table("unicode_fold_data", fold_records(folds)),
        "unicode_turkic_data.lani": table("unicode_turkic_data", fold_records(turkic)),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=ROOT / "data/unicode" / VERSION)
    parser.add_argument("--output", type=Path, default=ROOT / "stdlib/core")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate(args.data)
    for name, source in generated.items():
        path = args.output / name
        if args.check:
            assert path.read_text() == source, f"stale generated table: {path}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(source)
        print(f"{name}: {len(source)} bytes")


if __name__ == "__main__":
    main()
