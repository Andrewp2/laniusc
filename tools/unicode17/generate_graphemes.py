#!/usr/bin/env python3
"""Transform vendored Unicode 17 UCD property files into static Lanius ranges.

This is build-time data transformation only. Segmentation lives in Lanius.
No Python Unicode properties or host segmentation libraries are consulted.
"""
from __future__ import annotations

import argparse
import gzip
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GCB = dict(Other=0, CR=1, LF=2, Control=3, Extend=4, ZWJ=5,
           Regional_Indicator=6, Prepend=7, SpacingMark=8, L=9, V=10,
           T=11, LV=12, LVT=13)
INCB = dict(None_=0, Consonant=1, Extend=2, Linker=3)


def records(path: Path):
    opener = gzip.open if path.suffix == ".gz" else open
    with opener(path, "rt", encoding="utf-8") as source:
        for line in source:
            body = line.split("#", 1)[0].strip()
            if not body:
                continue
            fields = [part.strip() for part in body.split(";")]
            span = fields[0].split("..")
            yield int(span[0], 16), int(span[-1], 16), fields[1:]


def data_file(root: Path, name: str) -> Path:
    path = root / name
    if path.exists():
        return path
    return path.with_suffix(path.suffix + ".gz")


def generate(source: Path) -> str:
    values = bytearray(0x110000)
    for first, last, fields in records(data_file(source, "auxiliary/GraphemeBreakProperty.txt")):
        for codepoint in range(first, last + 1):
            assert values[codepoint] & 15 == 0
            values[codepoint] |= GCB[fields[0]]
    for first, last, fields in records(data_file(source, "DerivedCoreProperties.txt")):
        if fields[0] == "InCB":
            for codepoint in range(first, last + 1):
                assert values[codepoint] & 48 == 0
                values[codepoint] |= INCB[fields[1]] << 4
    for first, last, fields in records(data_file(source, "emoji/emoji-data.txt")):
        if fields[0] == "Extended_Pictographic":
            for codepoint in range(first, last + 1):
                values[codepoint] |= 64
    # Every modern Hangul syllable's GCB is computed arithmetically at lookup.
    for codepoint in range(0xAC00, 0xD7A4):
        assert values[codepoint] == (12 if (codepoint - 0xAC00) % 28 == 0 else 13)
        values[codepoint] = 0
    ranges = []
    first = 0
    for codepoint in range(1, len(values) + 1):
        if codepoint == len(values) or values[codepoint] != values[first]:
            if values[first]:
                ranges.append((first, codepoint - 1, values[first]))
            first = codepoint
    encoded = "".join(f"{first:06X}{last:06X}{flags:02X}" for first, last, flags in ranges)
    return f'''// Generated by tools/unicode17/generate_graphemes.py. Do not edit.
// Unicode 17.0.0: GraphemeBreakProperty, DerivedCoreProperties (InCB),
// emoji-data (Extended_Pictographic). See data/unicode/17.0.0 provenance.
// Copyright (c) 1991-2025 Unicode, Inc. Distributed under Unicode License v3;
// see data/unicode/17.0.0/LICENSE.txt.
// {len(ranges)} sorted disjoint nondefault ranges; 14 ASCII bytes per record.
module ext::unicode_graphemes_data;
import core::mem;

fn hex(bytes: [u8], start: i32, count: i32) -> u32 {{
    let value: u32 = 0;
    let index: i32 = 0;
    while (index < count) {{
        let digit: u32 = bytes[start + index] as u32;
        if (digit <= 57) {{ value = value * 16 + digit - 48; }}
        else {{ value = value * 16 + digit - 55; }}
        index += 1;
    }}
    return value;
}}

pub fn flags(value: u32) -> u32 {{
    if (value >= 44032 && value <= 55203) {{
        if ((value - 44032) % 28 == 0) {{ return 12; }}
        return 13;
    }}
    let bytes: [u8] = core::mem::typed_slice_from_raw_parts<u8>(core::mem::string_data_ptr("{encoded}"), {len(encoded)});
    let low: i32 = 0;
    let high: i32 = {len(ranges)};
    while (low < high) {{
        let middle: i32 = low + (high - low) / 2;
        let at: i32 = middle * 14;
        if (value < hex(bytes, at, 6)) {{ high = middle; }}
        else {{
            if (value > hex(bytes, at + 6, 6)) {{ low = middle + 1; }}
            else {{ return hex(bytes, at + 12, 2); }}
        }}
    }}
    return 0;
}}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path, default=ROOT / "data/unicode/17.0.0")
    parser.add_argument("--output", type=Path, default=ROOT / "extended/ext/unicode_graphemes_data.lani")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate(args.data_dir)
    if args.check:
        if args.output.read_text(encoding="utf-8") != generated:
            raise SystemExit(f"generated data differs: {args.output}")
    else:
        args.output.write_text(generated, encoding="utf-8")


if __name__ == "__main__":
    main()
