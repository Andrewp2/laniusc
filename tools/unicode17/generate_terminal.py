#!/usr/bin/env python3
"""Transform pinned Unicode 17 properties into static Lanius width-policy data.

This is build-time data transformation only. Terminal width lives in Lanius.
No Python Unicode properties or host width libraries are consulted.
"""
from __future__ import annotations

import argparse
import gzip
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ADDITIONAL_INPUTS = {
    "terminal-EastAsianWidth.txt.gz":
        "ea7ce50f3444a050333448dffef1cadd9325af55cbb764b4a2280faf52170a33",
    "terminal-emoji-variation-sequences.txt.gz":
        "bb3d09ef03f206012c7532dd52dc0a21c9efddba0135ea4cf0d9201b8b9bba7e",
}


def records(path: Path):
    with gzip.open(path, "rt", encoding="utf-8") as source:
        for line in source:
            body = line.split("#", 1)[0].strip()
            if not body:
                continue
            fields = [part.strip() for part in body.split(";")]
            span = fields[0].split("..")
            yield int(span[0], 16), int(span[-1], 16), fields[1:]


def generate(source: Path) -> str:
    for name, expected in ADDITIONAL_INPUTS.items():
        actual = hashlib.sha256(gzip.decompress((source / name).read_bytes())).hexdigest()
        if actual != expected:
            raise ValueError(f"Unicode 17 source checksum mismatch: {name}")
    values = bytearray(0x110000)
    for first, last, fields in records(source / "terminal-EastAsianWidth.txt.gz"):
        for cp in range(first, last + 1):
            if fields[0] in ("W", "F"):
                values[cp] |= 2
            if fields[0] == "A":
                values[cp] |= 4
    pending = None
    with gzip.open(source / "UnicodeData.txt.gz", "rt", encoding="utf-8") as file:
        for line in file:
            fields = line.rstrip().split(";")
            cp = int(fields[0], 16)
            if fields[1].endswith(", First>"):
                pending = cp
                continue
            first = pending if fields[1].endswith(", Last>") else cp
            assert first is not None
            pending = None
            for value in range(first, cp + 1):
                if fields[2].startswith("M") or fields[2] == "Cf":
                    values[value] |= 1
                if fields[2] in ("Cc", "Zl", "Zp"):
                    values[value] |= 64
    for name, properties, flag in [
        ("DerivedCoreProperties.txt.gz", {"Default_Ignorable_Code_Point"}, 1),
        ("PropList.txt.gz", {"Bidi_Control"}, 64),
        ("auxiliary/GraphemeBreakProperty.txt.gz", {"V", "T"}, 1),
    ]:
        for first, last, fields in records(source / name):
            if fields[0] in properties:
                for cp in range(first, last + 1):
                    values[cp] |= flag
    for first, last, fields in records(source / "emoji/emoji-data.txt.gz"):
        flag = {"Emoji": 8, "Emoji_Presentation": 16, "Emoji_Modifier": 1}.get(fields[0], 0)
        for cp in range(first, last + 1):
            values[cp] |= flag
    with gzip.open(source / "terminal-emoji-variation-sequences.txt.gz", "rt", encoding="utf-8") as file:
        for line in file:
            body = line.split("#", 1)[0].strip()
            if body:
                values[int(body.split()[0], 16)] |= 32
    ranges = []
    first = 0
    for cp in range(1, len(values) + 1):
        if cp == len(values) or values[cp] != values[first]:
            if values[first]:
                ranges.append((first, cp - 1, values[first]))
            first = cp
    encoded = "".join(f"{first:06X}{last:06X}{flags:02X}" for first, last, flags in ranges)
    return (TEMPLATE.replace("@COUNT@", str(len(ranges)))
            .replace("@LENGTH@", str(len(encoded))).replace("@DATA@", encoded))


TEMPLATE = '''// Generated by tools/unicode17/generate_terminal.py. Unicode 17.0.0.
// Static policy properties; see docs/extended-terminal.md and terminal-SOURCES.md.
// Copyright (c) 1991-2025 Unicode, Inc. Unicode License v3 (UCD LICENSE.txt).
// @COUNT@ sorted ranges; zero=1 W/F=2 A=4 Emoji=8 EmojiPresentation=16
// variation-base=32 rejected-control=64. Runtime policy lives in ext::terminal.
module ext::terminal_data;
import core::mem;
fn hex(bytes: [u8], start: i32, count: i32) -> u32 {
    let value: u32 = 0; let index: i32 = 0;
    while (index < count) {
        let digit: u32 = bytes[start + index] as u32;
        if (digit <= 57) { value = value * 16 + digit - 48; }
        else { value = value * 16 + digit - 55; }
        index += 1;
    }
    return value;
}
pub fn flags(value: u32) -> u32 {
    let bytes: [u8] = core::mem::typed_slice_from_raw_parts<u8>(core::mem::string_data_ptr("@DATA@"), @LENGTH@);
    let low: i32 = 0; let high: i32 = @COUNT@;
    while (low < high) {
        let middle: i32 = low + (high - low) / 2; let at: i32 = middle * 14;
        if (value < hex(bytes,at,6)) { high = middle; }
        else { if (value > hex(bytes,at+6,6)) { low = middle + 1; } else { return hex(bytes,at+12,2); } }
    }
    return 0;
}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path, default=ROOT / "data/unicode/17.0.0")
    parser.add_argument("--output", type=Path, default=ROOT / "extended/ext/terminal_data.lani")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate(args.data_dir)
    if args.check:
        if args.output.read_text(encoding="utf-8") != generated:
            raise SystemExit(f"generated terminal data differs: {args.output}")
    else:
        args.output.write_text(generated, encoding="utf-8")


if __name__ == "__main__":
    main()
