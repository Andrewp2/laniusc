#!/usr/bin/env python3
"""Generate Unicode 17 full casing overrides from the pinned UCD.

Production casing is Lanius. This generator never invokes host Unicode casing.
"""
import argparse
import gzip
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
UCD = ROOT / 'data/unicode/17.0.0'
TARGET = ROOT / 'extended/ext/unicode_case_data.lani'


def read(name):
    manifest = json.loads((UCD / 'manifest.json').read_text())
    assert manifest['unicode_version'] == '17.0.0'
    record = next(x for x in manifest['files'] if x['file'] == name + '.gz')
    compressed = (UCD / record['file']).read_bytes()
    assert hashlib.sha256(compressed).hexdigest() == record['gzip_sha256']
    original = gzip.decompress(compressed)
    assert len(original) == record['bytes']
    assert hashlib.sha256(original).hexdigest() == record['sha256']
    return original.decode('utf-8')


def generate():
    contexts = {'Final_Sigma': 1, 'After_Soft_Dotted': 2, 'More_Above': 3,
                'Before_Dot': 4, 'After_I': 5, 'Not_Before_Dot': 6}
    rows = set()
    for raw in read('SpecialCasing.txt').splitlines():
        line = raw.split('#', 1)[0].strip()
        if not line:
            continue
        fields = [x.strip() for x in line.split(';')]
        assert len(fields) in (5, 6) and not fields[-1]
        value = int(fields[0], 16)
        maps = [tuple(int(x, 16) for x in field.split()) for field in fields[1:4]]
        assert all(len(m) <= 3 for m in maps)
        assert all(0 <= x <= 0x10ffff and not 0xd800 <= x <= 0xdfff for m in maps for x in m)
        locale, context = 0, 0
        for condition in fields[4].split():
            if condition in ('tr', 'az', 'lt'):
                assert locale == 0
                locale = 1 if condition == 'lt' else 2
            else:
                assert context == 0 and condition in contexts, condition
                context = contexts[condition]
        packed = ''.join(f'{len(m):01X}' + ''.join(f'{x:06X}' for x in m + (0,) * (3-len(m))) for m in maps)
        rows.add((value, locale, context, packed))
    rows = sorted(rows)
    packed = ''.join(f'{v:06X}{loc:X}{ctx:X}{mapping}' for v, loc, ctx, mapping in rows)
    assert len(packed) == len(rows) * 65
    soft = []
    for raw in read('PropList.txt').splitlines():
        fields = [x.strip() for x in raw.split('#', 1)[0].split(';')]
        if len(fields) > 1 and fields[1] == 'Soft_Dotted':
            bounds = fields[0].split('..')
            soft.append((int(bounds[0], 16), int(bounds[-1], 16)))
    soft.sort()
    assert soft and all(soft[i-1][1] < soft[i][0] for i in range(1, len(soft)))
    soft_packed = ''.join(f'{a:06X}{b:06X}' for a,b in soft)
    return f'''// Generated by tools/unicode17/generate_case.py; do not edit.
// Unicode 17.0.0 SpecialCasing + PropList; data/unicode/17.0.0/LICENSE.txt.
// Copyright (c) 1991-2025 Unicode, Inc. Distributed under Unicode License v3.
// Locale: 0=any, 1=lt, 2=tr/az. Mapping kind: 0=lower, 1=title, 2=upper.
// Context: 0=always, 1=Final_Sigma, 2=After_Soft_Dotted, 3=More_Above,
// 4=Before_Dot, 5=After_I, 6=Not_Before_Dot.
module ext::unicode_case_data;
import core::mem;

pub struct Mapping {{ length: i32, first: u32, second: u32, third: u32 }}
pub const ROWS: i32 = {len(rows)};
fn number(data: [u8], at: i32, width: i32) -> u32 {{
    let value: u32 = 0; let index: i32 = 0;
    while (index < width) {{
        let byte: u8 = data[at + index]; let digit: u32 = (byte - 48) as u32;
        if (byte >= 65) {{ digit = (byte - 55) as u32; }}
        value = value * 16 + digit; index += 1;
    }}
    return value;
}}
fn read(index: i32, offset: i32, width: i32) -> u32 {{
    let packed: str = "{packed}";
    let data: [u8] = core::mem::typed_slice_from_raw_parts(core::mem::string_data_ptr(packed), {len(packed)});
    return number(data, index * 65 + offset, width);
}}
pub fn key(index: i32) -> u32 {{ return read(index, 0, 6); }}
pub fn locale(index: i32) -> u32 {{ return read(index, 6, 1); }}
pub fn context(index: i32) -> u32 {{ return read(index, 7, 1); }}
pub fn mapping(index: i32, kind: i32) -> Mapping {{
    let offset: i32 = 8 + kind * 19;
    return Mapping {{ length: read(index, offset, 1) as i32, first: read(index, offset + 1, 6), second: read(index, offset + 7, 6), third: read(index, offset + 13, 6) }};
}}
pub fn find(value: u32) -> i32 {{
    let low: i32 = 0; let high: i32 = ROWS;
    while (low < high) {{
        let middle: i32 = low + (high - low) / 2;
        if (key(middle) < value) {{ low = middle + 1; }} else {{ high = middle; }}
    }}
    if (low < ROWS && key(low) == value) {{ return low; }}
    return -1;
}}
pub fn soft_dotted(value: u32) -> bool {{
    let packed: str = "{soft_packed}";
    let data: [u8] = core::mem::typed_slice_from_raw_parts(core::mem::string_data_ptr(packed), {len(soft_packed)});
    let low: i32 = 0; let high: i32 = {len(soft)};
    while (low < high) {{
        let middle: i32 = low + (high - low) / 2;
        if (value < number(data, middle * 12, 6)) {{ high = middle; }}
        else {{ if (value > number(data, middle * 12 + 6, 6)) {{ low = middle + 1; }} else {{ return true; }} }}
    }}
    return false;
}}
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate()
    if args.check:
        assert TARGET.read_text() == result, f'stale generated table: {TARGET}'
    else:
        TARGET.write_text(result)
