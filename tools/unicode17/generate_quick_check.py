#!/usr/bin/env python3
"""Translate vendored Unicode 17.0.0 data into a two-level normalization table.

Each code point maps to one 14-bit entry:
  bits 0-7   Canonical_Combining_Class
  bit  8     NFD_QC=No   (has a canonical decomposition, Hangul included)
  bit  9     NFKD_QC=No  (has a canonical or compatibility decomposition)
  bits 10-11 NFC_QC      (0 Yes, 1 No, 2 Maybe)
  bits 12-13 NFKC_QC     (0 Yes, 1 No, 2 Maybe)
The table is stage1[cp >> 7] -> block, stage2[block][cp & 127] -> slot,
values[slot] -> entry: three fixed-width hex reads, no search. Inputs are
UnicodeData.txt and DerivedNormalizationProps.txt under data/unicode/17.0.0
(hash-checked against the manifest). The host unicodedata module is not read:
it describes an older Unicode version and is only used as a test oracle
(tools/unicode17/python_oracle.py).
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_normalization import read, ranges  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "extended/ext/unicode_quick_check_data.lani"
BLOCK = 128


def quick_check(text, name):
    values = {}
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        fields = [x.strip() for x in line.split(";")]
        if len(fields) == 3 and fields[1] == name:
            bounds = fields[0].split("..")
            for cp in range(int(bounds[0], 16), int(bounds[-1], 16) + 1):
                values[cp] = {"N": 1, "M": 2}[fields[2]]
    return values


def generate():
    ccc = {}
    canonical_pairs = []
    decomposable = set()
    for line in read("UnicodeData.txt").splitlines():
        fields = line.split(";")
        cp = int(fields[0], 16)
        if fields[3] != "0":
            ccc[cp] = int(fields[3])
        if fields[5]:
            decomposable.add(cp)
            if not fields[5].startswith("<"):
                canonical_pairs.append((cp, [int(x, 16) for x in fields[5].split()]))
    props = read("DerivedNormalizationProps.txt")
    qc = {name: quick_check(props, name) for name in ("NFD_QC", "NFKD_QC", "NFC_QC", "NFKC_QC")}
    assert set(qc["NFD_QC"].values()) == {1} and set(qc["NFKD_QC"].values()) == {1}
    exclusions = ranges(props, "Full_Composition_Exclusion")
    # The normalizer only tries composition when the second scalar is NFC_QC=Maybe
    # and only looks up decompositions when the D bits say No. Prove both.
    for cp, parts in canonical_pairs:
        if cp not in exclusions:
            assert len(parts) == 2 and qc["NFC_QC"].get(parts[1]) == 2, hex(cp)
    for cp in decomposable:
        assert qc["NFKD_QC"].get(cp) == 1, hex(cp)
    for cp, _ in canonical_pairs:
        assert qc["NFD_QC"].get(cp) == 1, hex(cp)
    for cp in range(0x1161, 0x1176):
        assert qc["NFC_QC"].get(cp) == 2
    for cp in range(0x11A8, 0x11C3):
        assert qc["NFC_QC"].get(cp) == 2
    for cp in range(0xAC00, 0xAC00 + 11172):
        assert qc["NFD_QC"].get(cp) == 1 and qc["NFKD_QC"].get(cp) == 1

    def entry(cp):
        return (ccc.get(cp, 0) | qc["NFD_QC"].get(cp, 0) << 8 | qc["NFKD_QC"].get(cp, 0) << 9
                | qc["NFC_QC"].get(cp, 0) << 10 | qc["NFKC_QC"].get(cp, 0) << 12)

    entries = [entry(cp) for cp in range(0x110000)]
    values = sorted(set(entries))
    slot = {v: i for i, v in enumerate(values)}
    assert len(values) <= 256
    blocks, stage1 = {}, []
    for b in range(0x110000 // BLOCK):
        key = tuple(slot[v] for v in entries[b * BLOCK:(b + 1) * BLOCK])
        stage1.append(blocks.setdefault(key, len(blocks)))
    assert len(blocks) <= 256
    stage2 = [s for key, _ in sorted(blocks.items(), key=lambda kv: kv[1]) for s in key]
    s1 = "".join(f"{x:02X}" for x in stage1)
    s2 = "".join(f"{x:02X}" for x in stage2)
    s3 = "".join(f"{x:04X}" for x in values)
    out = [
        "// Generated by tools/unicode17/generate_quick_check.py; do not edit.",
        "// Unicode 17.0.0 UnicodeData + DerivedNormalizationProps; see data/unicode/17.0.0.",
        "// Copyright (c) 1991-2025 Unicode, Inc. Distributed under Unicode License v3;",
        "// see data/unicode/17.0.0/LICENSE.txt.",
        f"// Two-level table: {len(stage1)} stage-1 blocks of {BLOCK}, {len(blocks)} distinct blocks,",
        f"// {len(values)} distinct entries. Entry bits: ccc 0-7, NFD_QC=N 8, NFKD_QC=N 9,",
        "// NFC_QC 10-11 and NFKC_QC 12-13 (0 Yes, 1 No, 2 Maybe).",
        "module ext::unicode_quick_check_data;", "import core::mem;", "",
        "fn number(data: [u8], at: i32, width: i32) -> u32 {",
        "    let value: u32 = 0; let index: i32 = 0;",
        "    while (index < width) {",
        "        let byte: u8 = data[at + index]; let digit: u32 = (byte - 48) as u32;",
        "        if (byte >= 65) { digit = (byte - 55) as u32; }",
        "        value = value * 16 + digit; index += 1;",
        "    }", "    return value;", "}", "",
        "// Precondition: value <= 0x10FFFF.",
        "pub fn entry(value: u32) -> u32 {",
        f'    let first: str = "{s1}";',
        f"    let stage1: [u8] = core::mem::typed_slice_from_raw_parts(core::mem::string_data_ptr(first), {len(s1)});",
        f'    let second: str = "{s2}";',
        f"    let stage2: [u8] = core::mem::typed_slice_from_raw_parts(core::mem::string_data_ptr(second), {len(s2)});",
        f'    let third: str = "{s3}";',
        f"    let stage3: [u8] = core::mem::typed_slice_from_raw_parts(core::mem::string_data_ptr(third), {len(s3)});",
        "    let block: u32 = number(stage1, ((value >> 7) * 2) as i32, 2);",
        "    let slot: u32 = number(stage2, (((block << 7) + (value & 127)) * 2) as i32, 2);",
        "    return number(stage3, (slot * 4) as i32, 4);",
        "}", "",
    ]
    return "\n".join(out)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = generate()
    if args.check:
        assert TARGET.read_text() == source, f"stale generated table: {TARGET}"
    else:
        TARGET.write_text(source)
