#!/usr/bin/env python3
"""Translate the vendored Unicode 17 UCD into Lanius normalization tables.

No host Unicode database or normalizer is used. The production normalizer is
extended/ext/unicode_normalize.lani; this program only transforms UCD tables.
"""
import argparse
import functools
import gzip
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
UCD = ROOT / "data/unicode/17.0.0"
TARGET = ROOT / "extended/ext/unicode_normalize_data.lani"


def read(name):
    manifest = json.loads((UCD / "manifest.json").read_text())
    assert manifest["unicode_version"] == "17.0.0"
    record = next(x for x in manifest["files"] if x["file"] == name + ".gz")
    compressed = (UCD / record["file"]).read_bytes()
    assert hashlib.sha256(compressed).hexdigest() == record["gzip_sha256"]
    original = gzip.decompress(compressed)
    assert len(original) == record["bytes"]
    assert hashlib.sha256(original).hexdigest() == record["sha256"]
    return original.decode("utf-8")


def ranges(text, property_name):
    result = set()
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        fields = [x.strip() for x in line.split(";")]
        if len(fields) > 1 and fields[1] == property_name:
            bounds = fields[0].split("..")
            result.update(range(int(bounds[0], 16), int(bounds[-1], 16) + 1))
    return result


def generate():
    mappings = {}
    for line in read("UnicodeData.txt").splitlines():
        fields = line.split(";")
        if fields[5]:
            parts = fields[5].split()
            compatibility = parts[0].startswith("<")
            if compatibility:
                parts = parts[1:]
            mappings[int(fields[0], 16)] = (compatibility, tuple(int(x, 16) for x in parts))
    exclusions = ranges(read("DerivedNormalizationProps.txt"), "Full_Composition_Exclusion")
    explicit_exclusions = {
        int(line.split("#", 1)[0].strip(), 16)
        for line in read("CompositionExclusions.txt").splitlines()
        if line.split("#", 1)[0].strip()
    }
    assert explicit_exclusions <= exclusions

    active = set()

    @functools.cache
    def expand(value, compatibility):
        key = (value, compatibility)
        assert key not in active, "decomposition mapping cycle"
        active.add(key)
        if 0xAC00 <= value < 0xAC00 + 11172:
            offset = value - 0xAC00
            result = (0x1100 + offset // 588, 0x1161 + offset % 588 // 28)
            if offset % 28:
                result += (0x11A7 + offset % 28,)
            depth = 2 if offset % 28 else 1
        elif value in mappings and (compatibility or not mappings[value][0]):
            parts = [expand(x, compatibility) for x in mappings[value][1]]
            result = tuple(x for part, _ in parts for x in part)
            depth = 1 + max(d for _, d in parts)
        else:
            result, depth = (value,), 0
        assert result and all(x <= 0x10FFFF and not 0xD800 <= x <= 0xDFFF for x in result)
        active.remove(key)
        return result, depth

    tables = {}
    maxima = {}
    for name, compatibility in [("canonical", False), ("compatibility", True)]:
        rows, pool = [], []
        maximum, depth = 3, 2  # Algorithmic Hangul full decomposition.
        for value in sorted(mappings):
            expanded, mapping_depth = expand(value, compatibility)
            maximum = max(maximum, len(expanded))
            depth = max(depth, mapping_depth)
            if expanded != (value,):
                rows.append(f"{value:06X}{len(pool):06X}{len(expanded):02X}")
                pool.extend(expanded)
        assert len(pool) < 0x1000000 and maximum < 256
        tables[name] = ("".join(rows), "".join(f"{x:06X}" for x in pool))
        maxima[name] = (maximum, depth)

    pairs = []
    for value, (compatibility, parts) in mappings.items():
        if not compatibility and value not in exclusions:
            assert len(parts) == 2, "primary composite must have a pair mapping"
            pairs.append((parts[0], parts[1], value))
    pairs.sort()
    assert len({p[:2] for p in pairs}) == len(pairs)
    packed_pairs = "".join(f"{a:06X}{b:06X}{c:06X}" for a, b, c in pairs)

    output = [
        "// Generated by tools/unicode17/generate_normalization.py; do not edit.",
        "// Unicode 17.0.0 UnicodeData + DerivedNormalizationProps; see data/unicode/17.0.0.",
        "// Copyright (c) 1991-2025 Unicode, Inc. Distributed under Unicode License v3;",
        "// see data/unicode/17.0.0/LICENSE.txt.",
        "// Full decomposition DAG expanded at generation; runtime has no recursion.",
        "module ext::unicode_normalize_data;", "import core::mem;", "",
        "pub struct Mapping { offset: i32, length: i32 }",
    ]
    for name, (maximum, depth) in maxima.items():
        output += [f"pub const MAX_{name.upper()}_LENGTH: i32 = {maximum};",
                   f"pub const MAX_{name.upper()}_DEPTH: i32 = {depth};"]
    output += ["", "fn number(data: [u8], at: i32, width: i32) -> u32 {",
               "    let value: u32 = 0; let index: i32 = 0;",
               "    while (index < width) {",
               "        let byte: u8 = data[at + index]; let digit: u32 = (byte - 48) as u32;",
               "        if (byte >= 65) { digit = (byte - 55) as u32; }",
               "        value = value * 16 + digit; index += 1;",
               "    }", "    return value;", "}", ""]
    for name, (rows, pool) in tables.items():
        output += [f"pub fn {name}(value: u32) -> Mapping {{", f'    let packed: str = "{rows}";',
                   f"    let data: [u8] = core::mem::typed_slice_from_raw_parts(core::mem::string_data_ptr(packed), {len(rows)});",
                   f"    let low: i32 = 0; let high: i32 = {len(rows) // 14};",
                   "    while (low < high) {", "        let middle: i32 = low + (high - low) / 2;",
                   "        let key: u32 = number(data, middle * 14, 6);",
                   "        if (key < value) { low = middle + 1; }",
                   "        else { if (key > value) { high = middle; } else {",
                   "            return Mapping { offset: number(data, middle * 14 + 6, 6) as i32, length: number(data, middle * 14 + 12, 2) as i32 };",
                   "        } }", "    }", "    return Mapping { offset: 0, length: 0 };", "}", "",
                   f"pub fn {name}_scalar(index: i32) -> u32 {{", f'    let packed: str = "{pool}";',
                   f"    let data: [u8] = core::mem::typed_slice_from_raw_parts(core::mem::string_data_ptr(packed), {len(pool)});",
                   "    return number(data, index * 6, 6);", "}", ""]
    output += ["pub fn compose(left: u32, right: u32) -> u32 {", f'    let packed: str = "{packed_pairs}";',
               f"    let data: [u8] = core::mem::typed_slice_from_raw_parts(core::mem::string_data_ptr(packed), {len(packed_pairs)});",
               f"    let low: i32 = 0; let high: i32 = {len(pairs)};",
               "    while (low < high) {", "        let middle: i32 = low + (high - low) / 2;",
               "        let first: u32 = number(data, middle * 18, 6);",
               "        let second: u32 = number(data, middle * 18 + 6, 6);",
               "        if (first < left || (first == left && second < right)) { low = middle + 1; }",
               "        else { if (first > left || (first == left && second > right)) { high = middle; }",
               "        else { return number(data, middle * 18 + 12, 6); } }",
               "    }", "    return 4294967295;", "}", ""]
    return "\n".join(output)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = generate()
    if args.check:
        assert TARGET.read_text() == source, f"stale generated table: {TARGET}"
    else:
        TARGET.write_text(source)
