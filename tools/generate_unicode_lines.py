#!/usr/bin/env python3
"""Generate Unicode 17 default line-break property data, offline.

Only static properties are generated. The ordered UAX #14 algorithm is Lanius.
No host Unicode database, segmentation package or locale is consulted.
"""
import argparse
from array import array
import gzip
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
N = 0x110000
CLASSES = 'AL BK CR LF NL SP ZW ZWJ CM WJ GL BA HY HH CL CP EX SY OP QU IS NS B2 CB BB HL IN NU PR PO ID EB EM JL JV JT H2 H3 AP AK AS VF VI RI'.split()
LB = {name: index + 1 for index, name in enumerate(CLASSES)}

def source(root, name):
    return gzip.decompress((root / ('unicode-lines-' + name + '.gz')).read_bytes()).decode('utf-8')

def records(text):
    for line in text.splitlines():
        body = line.split('#', 1)[0].strip()
        if body:
            span, value = (part.strip() for part in body.split(';', 1))
            ends = span.split('..')
            yield int(ends[0], 16), int(ends[-1], 16), value

def generate(root):
    manifest = json.loads((root / 'unicode-lines-manifest.json').read_text())
    for item in manifest.values():
        raw = gzip.decompress((root / item['path']).read_bytes())
        assert len(raw) == item['bytes'] and hashlib.sha256(raw).hexdigest() == item['sha256'], item['path']
    category = bytearray(N)  # Cn=0, Pi=1, Pf=2, Mn/Mc=3, other assigned=4
    for first, last, value in records(source(root, 'DerivedGeneralCategory.txt')):
        code = {'Cn': 0, 'Pi': 1, 'Pf': 2, 'Mn': 3, 'Mc': 3}.get(value, 4)
        category[first:last+1] = bytes([code]) * (last-first+1)
    values = array('H', [LB['AL']]) * N
    raw_lb = source(root, 'DerivedLineBreak.txt')
    aliases = {'Unknown': 'AL', 'Prefix_Numeric': 'PR', 'Ideographic': 'ID'}
    for line in raw_lb.splitlines():
        if '@missing:' in line:
            for first, last, value in records(line.split('@missing:', 1)[1]):
                values[first:last+1] = array('H', [LB[aliases[value]]]) * (last-first+1)
    for first, last, value in records(raw_lb):
        for cp in range(first, last+1):
            resolved = 'AL' if value in ('AI', 'SG', 'XX') else 'NS' if value == 'CJ' else ('CM' if category[cp] == 3 else 'AL') if value == 'SA' else value
            values[cp] = LB[resolved]
    for first, last, value in records(source(root, 'EastAsianWidth.txt')):
        if value in ('F', 'W', 'H'):
            for cp in range(first, last+1): values[cp] |= 64
    for cp, gc in enumerate(category):
        if gc == 1: values[cp] |= 128
        if gc == 2: values[cp] |= 256
    for first, last, value in records(source(root, 'emoji-data.txt')):
        if value == 'Extended_Pictographic':
            for cp in range(first, last+1):
                if category[cp] == 0: values[cp] |= 512
    values[0x25CC] |= 1024
    for cp in range(0xAC00, 0xD7A4):
        assert values[cp] == 64 | LB['H2' if (cp-0xAC00) % 28 == 0 else 'H3']
        values[cp] = LB['AL']
    ranges = []
    first = 0
    for cp in range(1, N+1):
        if cp == N or values[cp] != values[first]:
            if values[first] != LB['AL']: ranges.append((first, cp-1, values[first]))
            first = cp
    encoded = ''.join(f'{first:06X}{last:06X}{flags:04X}' for first,last,flags in ranges)
    return f'''// Generated by tools/generate_unicode_lines.py; do not edit.
// Unicode 17.0.0 default LB1 resolution + EAW(F/W/H), Pi, Pf,
// Extended_Pictographic & Cn, and U+25CC. No line-breaking code is generated.
// Unicode data copyright 1991-2025 Unicode, Inc.; Unicode License v3:
// data/unicode/17.0.0/LICENSE.txt. Provenance: unicode-lines-manifest.json.
// {len(ranges)} sorted nondefault ranges, 16 ASCII bytes per record.
module ext::unicode_lines_data;
import core::mem;
fn hex(bytes: [u8], start: i32, count: i32) -> u32 {{
    let result: u32 = 0; let i: i32 = 0;
    while (i < count) {{ let digit: u32 = bytes[start+i] as u32; result *= 16; if (digit <= 57) {{ result += digit-48; }} else {{ result += digit-55; }} i += 1; }} return result;
}}
pub fn flags(value: u32) -> u32 {{
    if (value >= 44032 && value <= 55203) {{ if ((value-44032)%28 == 0) {{ return 101; }} return 102; }}
    let bytes: [u8] = core::mem::typed_slice_from_raw_parts<u8>(core::mem::string_data_ptr("{encoded}"),{len(encoded)});
    let low: i32 = 0; let high: i32 = {len(ranges)};
    while (low < high) {{ let middle: i32 = low+(high-low)/2; let at: i32 = middle*16;
        if (value < hex(bytes,at,6)) {{ high = middle; }} else {{ if (value > hex(bytes,at+6,6)) {{ low = middle+1; }} else {{ return hex(bytes,at+12,4); }} }}
    }} return 1;
}}
'''

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data-dir', type=Path, default=ROOT / 'data/unicode/17.0.0')
    parser.add_argument('--output', type=Path, default=ROOT / 'extended/ext/unicode_lines_data.lani')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(); generated = generate(args.data_dir)
    if args.check:
        if args.output.read_text() != generated: raise SystemExit('generated Unicode line data differs')
    else: args.output.write_text(generated)

if __name__ == '__main__': main()
