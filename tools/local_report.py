#!/usr/bin/env python3
"""Write the ranked report of kernels with per-thread local arrays (markdown).

usage: tools/local_report.py [--sizes INLINED_SIZES.txt] [--measured MEASURED.md] [--out OUT.md]

--sizes is the shader build's report (default
target/laniusc-shader-artifacts/release/inlined_sizes.txt), whose `local`
column is the written local array bytes along the deepest call chain
(`local_bytes` in crates/laniusc-shaders/spirv_size.rs; tools/spv_local_bytes.py
computes the same figure for single modules). --measured optionally adds the
driver's figures from a tools/local_memory_report.py table. The report goes to
--out (default target/claude-work/reports/local_arrays.md).
"""
import argparse
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = 1024
AREAS = ('type_checker', 'codegen', 'parser', 'lexer', 'tests')

parser = argparse.ArgumentParser()
parser.add_argument('--sizes', default=ROOT / 'target/laniusc-shader-artifacts/release/inlined_sizes.txt')
parser.add_argument('--measured')
parser.add_argument('--out', default=ROOT / 'target/claude-work/reports/local_arrays.md')
args = parser.parse_args()

rows, total = [], 0
for line in open(args.sizes):
    fields = line.split()
    if len(fields) != 6 or not fields[0].isdigit():
        continue
    total += 1
    inlined, own, limit, local, local_limit = map(int, fields[:5])
    if local:
        rows.append((local, fields[5], inlined, own, limit, local_limit))
rows.sort(key=lambda r: (-r[0], r[1]))
measured = {}
if args.measured:
    for line in open(args.measured):
        m = re.match(r'\|\s*([\d,]+)\s*\|.*`([^`]+)`\s*\|\s*$', line)
        if m:
            measured[m.group(2)] = int(m.group(1).replace(',', ''))
commit = subprocess.run(['git', 'rev-parse', '--short', 'HEAD'], cwd=ROOT, capture_output=True,
                        text=True).stdout.strip()
dirty = subprocess.run(['git', 'status', '--porcelain', '--', 'shaders'], cwd=ROOT, capture_output=True,
                       text=True).stdout.strip()


def area(kernel):
    top = kernel.split('/')[0]
    return top if top in AREAS else 'other'


by_area = {}
for local, key, *_ in rows:
    n, over, s = by_area.get(area(key), (0, 0, 0))
    by_area[area(key)] = (n + 1, over + (local > TARGET), s + local)
over_total = sum(1 for r in rows if r[0] > TARGET)

out = [
    '# Kernels with per-thread local arrays',
    '',
    f'Generated by `tools/local_report.py` from `{args.sizes}` (shaders at {commit}'
    f'{" with uncommitted shader changes" if dirty else ""})'
    + (f' and the driver figures in `{args.measured}`.' if args.measured else '.'),
    '',
    'Regenerate after a release build:',
    '',
    '```',
    'python3 tools/local_report.py [--measured target/claude-work/reports/local_memory_measured.md]',
    '```',
    '',
    '## Why this list matters',
    '',
    'NVIDIA reserves local memory for the whole process: the largest per-thread figure of any created '
    'pipeline times ~61k resident threads, placed at pipeline creation and never shrunk. Kernels with '
    'per-thread arrays also run 20 to 300 times slower in warm daemon jobs. Data from the 1 MB seed-20 '
    'workload, PROBE_PROFILE traces:',
    '',
    '| kernel | local bytes | job 1 ms | job 2 ms |',
    '|---|---:|---:|---:|',
    '| type_checker/calls/03k1_project_literal_contexts (3 dispatches) | 3328 | 3.8 | 1042 |',
    '| parser/tokens/delimiter_match/03_enclosing_opens, old | 3840 | 2.5 | 46.7 |',
    '| parser/tokens/delimiter_match/03_enclosing_opens, rewritten (no local arrays) | 0 | 0.19 | 0.11 |',
    '| parser/tree/spans, old | 1536 | 1.33 | 26.9 |',
    '| parser/tree/spans, rewritten (no local arrays) | 0 | 0.29 | 0.33 |',
    '',
    f'The target is at most {TARGET} bytes per kernel, and none for new or rewritten kernels. The build '
    'enforces it as a ratchet: a kernel without a line in `crates/laniusc-shaders/local_array_budget.txt` '
    'may have no local arrays, and listed limits only go down (`tools/ratchet_inlined_budget.py`).',
    '',
    '## How the numbers are computed',
    '',
    '*local bytes* is what the kernel declares, as measured by the build (`local_bytes` in '
    '`crates/laniusc-shaders/spirv_size.rs`; `tools/spv_local_bytes.py --vars KERNEL.spv` lists the arrays):',
    '',
    '- A local array is a Function- or Private-storage `OpVariable` whose type is an array or a struct '
    'holding one.',
    '- Only written arrays count. A table that only ever holds constants is kept out of local memory by '
    'the driver and is not counted.',
    '- A function\'s arrays add to those of the callee that needs the most; sibling calls reuse the space.',
    '',
    '*driver* is the driver\'s own figure where measured (`shader_dispatch_replay --memory-probe`). It also '
    'counts register spills and the DontInline harness\'s call frames, and leaves out small arrays kept in '
    'registers.',
    '',
    f'Of {total} kernels, {len(rows)} have local arrays and {over_total} are over {TARGET} bytes:',
    '',
    f'| area | kernels | over {TARGET} B | sum of local bytes |',
    '|---|---:|---:|---:|',
]
for name, (n, over, s) in sorted(by_area.items(), key=lambda kv: -kv[1][2]):
    out.append(f'| {name} | {n} | {over} | {s} |')
out += [
    '',
    '## Ranked list',
    '',
    f'*over 1 KB* is the excess over {TARGET} bytes, the work left on that kernel.',
    '',
    '| # | kernel | local bytes | over 1 KB | driver | local budget | fully inlined | own | inlined budget |',
    '|---:|---|---:|---:|---:|---:|---:|---:|---:|',
]
for i, (local, key, inlined, own, limit, local_limit) in enumerate(rows, 1):
    excess = f'+{local - TARGET}' if local > TARGET else 'no'
    driver = measured.get(key, '')
    out.append(f'| {i} | {key} | {local} | {excess} | {driver} | {local_limit} | {inlined} | {own} | {limit} |')
out.append('')
pathlib.Path(args.out).write_text('\n'.join(out))
print(f'wrote {args.out}: {len(rows)} kernels with local arrays, {over_total} over {TARGET} bytes')
