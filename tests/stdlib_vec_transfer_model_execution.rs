//! Ordered owner transfers, complete generic payloads and capacity contracts.
#![cfg(all(target_os = "linux", target_arch = "x86_64"))]
mod common;

use std::{fs, os::unix::fs::PermissionsExt, path::PathBuf, process::Command, time::Duration};

fn fixture(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/stdlib_vec_transfer_model")
        .join(name)
}

#[test]
fn vector_transfers_match_ordered_owner_states_payloads_and_capacity_contracts() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let entry = fixture("model.lani");
    let roots = laniusc_compiler::compiler::EntrySourceRoots {
        stdlib_root: Some(root.join("stdlib")),
        user_roots: vec![],
    };
    let bytes =
        common::run_gpu_codegen_with_timeout("vector ownership transfer model", move || {
            pollster::block_on(
                laniusc_compiler::compiler::compile_entry_to_x86_64_with_source_roots(
                    &entry, &roots,
                ),
            )
        })
        .unwrap_or_else(|error| panic!("vector ownership transfer model: {error}"));
    assert!(common::x86_jumps::is_x86_64_executable(&bytes));
    let executable = common::TempArtifact::new("laniusc_vec_transfer_model", "model", None);
    executable.write_bytes(bytes);
    fs::set_permissions(executable.path(), fs::Permissions::from_mode(0o700)).unwrap();
    let output = common::process_output_with_timeout(
        "independent vector transfer owner reference",
        Command::new("python3")
            .arg("-B")
            .arg(fixture("oracle.py"))
            .arg(executable.path()),
        Duration::from_secs(90),
    );
    common::assert_command_success("vector ownership transfer model", &output);
    assert!(output.stderr.is_empty(), "{output:?}");
    let summary = String::from_utf8(output.stdout).unwrap();
    assert_eq!(
        summary,
        "vec-transfer-model cases=56 actions=3584 created=787 nested_owners=170 moved_items=3698 nonempty_transfers=913 empty_transfers=397 bounds_errors=242 capacity_errors=112 saved_views=1049 snapshot_entries=28352 shapes=5 seed=0x7ec7a0261114\n"
    );
    eprint!("{summary}");
}
